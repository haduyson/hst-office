"""Stage the LibreOffice --with-branding directory for the HST build.

Usage: .venv/bin/python scripts/stage-branding.py [--out build/branding-staging]

configure fixes the list of custom brand files when it runs, so every expected
file must exist before configure. Final artwork lives in branding/libreoffice/
(generated by scripts/generate-brand-assets.py); any file not produced there
yet is rendered here from the approved HST logo at the upstream default size,
and the manifest records which source each staged file came from. Re-run after
the final assets change, then rebuild the `desktop` module to repackage.
"""
import argparse
import base64
import io
import json
import os
import shutil

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FINAL_DIR = os.path.join(ROOT, "branding", "libreoffice")
LOGO = os.path.join(ROOT, "assets", "brand", "hst-office-logo.png")
MARK = os.path.join(ROOT, "assets", "brand", "hst-office-mark.png")

# Upstream default sizes measured in icon-themes/colibre/brand at 26.8.1.1.
PNG_SIZES = {"intro.png": (644, 199), "intro-highres.png": (990, 254), "donate1.png": (200, 200), "donate2.png": (150, 150)}
SVG_SIZES = {"logo.svg": (345.611, 71.5), "logo_inverted.svg": (345.611, 71.5), "logo-sc.svg": (345.611, 71.5),
             "logo-sc_inverted.svg": (345.611, 71.5), "about.svg": (372.724, 354.728)}
OPTIONAL_FILES = ["progress.conf"]
BANNER = "hst-banner.png"  # 1280x160 artwork, drawn at half size
BANNER = "hst-banner.png"  # 1280x160 artwork, drawn at half size


def fit(image, size, background):
    """Scale `image` to fit inside `size`, centred on a canvas."""
    canvas = Image.new("RGBA", size, background)
    scaled = image.copy()
    scaled.thumbnail((int(size[0] * 0.9), int(size[1] * 0.9)), Image.LANCZOS)
    canvas.alpha_composite(scaled, ((size[0] - scaled.width) // 2, (size[1] - scaled.height) // 2))
    return canvas


def png_bytes(image):
    buffer = io.BytesIO()
    image.save(buffer, format="PNG", compress_level=9)
    return buffer.getvalue()


def render_interim(name):
    logo = Image.open(LOGO).convert("RGBA")
    mark = Image.open(MARK).convert("RGBA")
    if name in PNG_SIZES:
        size = PNG_SIZES[name]
        source = mark if name.startswith("donate") else logo
        background = (255, 255, 255, 255) if name.startswith("intro") else (0, 0, 0, 0)
        return png_bytes(fit(source, size, background))
    width, height = SVG_SIZES[name]
    source = mark if name == "about.svg" else logo
    raster = fit(source, (int(width * 4), int(height * 4)), (0, 0, 0, 0))
    data = base64.b64encode(png_bytes(raster)).decode("ascii")
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
            f'viewBox="0 0 {width} {height}"><image width="{width}" height="{height}" '
            f'href="data:image/png;base64,{data}"/></svg>\n').encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=os.path.join(ROOT, "build", "branding-staging"))
    args = parser.parse_args()
    os.makedirs(args.out, exist_ok=True)
    manifest = {}
    for name in list(PNG_SIZES) + list(SVG_SIZES):
        final = os.path.join(FINAL_DIR, name)
        # hst-start-center-banner.patch reads the Start Center banner from donate1.png.
        if name == "donate1.png" and os.path.exists(os.path.join(FINAL_DIR, BANNER)):
            final = os.path.join(FINAL_DIR, BANNER)
        # hst-start-center-banner.patch reads the Start Center banner from donate1.png.
        if name == "donate1.png" and os.path.exists(os.path.join(FINAL_DIR, BANNER)):
            final = os.path.join(FINAL_DIR, BANNER)
        target = os.path.join(args.out, name)
        if os.path.exists(final):
            shutil.copyfile(final, target)
            manifest[name] = "final:branding/libreoffice"
        else:
            with open(target, "wb") as handle:
                handle.write(render_interim(name))
            manifest[name] = "interim:rendered-from-assets/brand"
    for name in OPTIONAL_FILES:
        final = os.path.join(FINAL_DIR, name)
        if os.path.exists(final):
            shutil.copyfile(final, os.path.join(args.out, name))
            manifest[name] = "final:branding/libreoffice"
    with open(os.path.join(args.out, "staging-manifest.json"), "w", encoding="utf-8") as handle:
        json.dump(manifest, handle, indent=2, sort_keys=True)
    print(json.dumps(manifest, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
