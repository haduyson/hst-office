"""Single source of truth for the HST Office release version.

Reads <repo>/VERSION (one line, MAJOR.MINOR.MICRO) and either
  --header PATH   write a C header (HST_VERSION, HST_VERSION_MAJOR/MINOR/MICRO),
                  rewriting the file only when its content changes so make does
                  not rebuild dependants needlessly;
  --env           print `export HST_VERSION_*=...` lines for `eval` in a shell;
  --print         print the version.
The LibreOffice engine version is independent and stays at the upstream value.
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def read_version(path=ROOT / "VERSION"):
    text = path.read_text(encoding="utf-8").strip()
    m = re.fullmatch(r"(\d+)\.(\d+)\.(\d+)", text)
    if not m:
        sys.exit(f"{path}: expected MAJOR.MINOR.MICRO, got {text!r}")
    return text, m.groups()


def header_text(version, parts):
    major, minor, micro = parts
    return (
        "/* Generated by scripts/write-hst-version.py from /VERSION. Do not edit. */\n"
        "#ifndef INCLUDED_HST_VERSION_H\n#define INCLUDED_HST_VERSION_H\n"
        f'#define HST_VERSION "{version}"\n'
        f"#define HST_VERSION_MAJOR {int(major)}\n#define HST_VERSION_MINOR {int(minor)}\n"
        f"#define HST_VERSION_MICRO {int(micro)}\n#endif\n"
    )


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--version-file", type=pathlib.Path, default=ROOT / "VERSION")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--header", type=pathlib.Path)
    g.add_argument("--env", action="store_true")
    g.add_argument("--print", action="store_true", dest="show")
    a = ap.parse_args()
    version, parts = read_version(a.version_file)
    if a.show:
        print(version)
    elif a.env:
        for k, v in zip(("MAJOR", "MINOR", "MICRO"), parts):
            print(f"export HST_VERSION_{k}={int(v)}")
        print(f"export HST_VERSION={version}")
    else:
        new = header_text(version, parts)
        if a.header.exists() and a.header.read_text(encoding="utf-8") == new:
            print(f"{a.header}: unchanged ({version})")
        else:
            a.header.parent.mkdir(parents=True, exist_ok=True)
            a.header.write_text(new, encoding="utf-8")
            print(f"{a.header}: written ({version})")


if __name__ == "__main__":
    main()
