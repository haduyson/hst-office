"""Single source of truth for the HST Office release version.

Reads <repo>/VERSION (one line, MAJOR.MINOR.MICRO) and <repo>/data/hst/release.json
(the full release id, e.g. 1.0.0-beta.4.1; its core must equal VERSION) and either
  --header PATH   write a C header (HST_VERSION, HST_VERSION_MAJOR/MINOR/MICRO,
                  HST_RELEASE, HST_VERSION_BUILD, HST_FILE_VERSION), rewriting the
                  file only when its content changes so make does not rebuild
                  dependants needlessly;
  --env           print `export HST_*=...` lines for `eval` in a shell;
  --print         print the version (MAJOR.MINOR.MICRO);
  --release       print the release id;
  --build         print the numeric build number.
The build number is the monotonic 4th component of Windows file/product versions, the
MSI ProductVersion and the macOS CFBundleVersion: beta.N[.M] -> N*100+M (N < 50),
rc.N[.M] -> 5000+N*100+M, final release -> 10000.
The LibreOffice engine version is independent and stays at the upstream value.
"""
import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FINAL_BUILD = 10000
RC_BASE = 5000
_PRERELEASE = re.compile(r"(beta|rc)\.(0|[1-9]\d*)(?:\.(0|[1-9]\d*))?")
_RELEASE = re.compile(r"(\d+\.\d+\.\d+)(?:-([0-9A-Za-z.-]+))?")


def read_version(path=ROOT / "VERSION"):
    text = path.read_text(encoding="utf-8").strip()
    m = re.fullmatch(r"(\d+)\.(\d+)\.(\d+)", text)
    if not m:
        sys.exit(f"{path}: expected MAJOR.MINOR.MICRO, got {text!r}")
    return text, m.groups()


def release_build(release):
    """Monotonic build number of a release id; raises ValueError for ids outside the scheme."""
    match = _RELEASE.fullmatch(release)
    if not match:
        raise ValueError(f"not a release id: {release!r}")
    if match.group(2) is None:
        return FINAL_BUILD
    pre = _PRERELEASE.fullmatch(match.group(2))
    if not pre:
        raise ValueError(f"unsupported pre-release {match.group(2)!r}: use beta.N[.M] or rc.N[.M]")
    major, minor = int(pre.group(2)), int(pre.group(3) or 0)
    if major > 49 or minor > 99:
        raise ValueError(f"pre-release {match.group(2)!r} out of range (N <= 49, M <= 99)")
    return (RC_BASE if pre.group(1) == "rc" else 0) + major * 100 + minor


def read_release(version, path=ROOT / "data" / "hst" / "release.json"):
    """Release id from release.json; its MAJOR.MINOR.MICRO must equal `version` (/VERSION)."""
    try:
        release = json.loads(path.read_text(encoding="utf-8"))["release"]
    except (OSError, ValueError, KeyError, TypeError) as exc:
        sys.exit(f"{path}: cannot read the release id: {exc}")
    if not isinstance(release, str) or not _RELEASE.fullmatch(release) or _RELEASE.fullmatch(release).group(1) != version:
        sys.exit(f"{path}: release {release!r} does not match /VERSION {version!r}")
    try:
        release_build(release)
    except ValueError as exc:
        sys.exit(f"{path}: {exc}")
    return release


def header_text(version, parts, release=None):
    major, minor, micro = parts
    release = release or version
    build = release_build(release)
    return (
        "/* Generated by scripts/write-hst-version.py from /VERSION. Do not edit. */\n"
        "#ifndef INCLUDED_HST_VERSION_H\n#define INCLUDED_HST_VERSION_H\n"
        f'#define HST_VERSION "{version}"\n'
        f"#define HST_VERSION_MAJOR {int(major)}\n#define HST_VERSION_MINOR {int(minor)}\n"
        f"#define HST_VERSION_MICRO {int(micro)}\n"
        f'#define HST_RELEASE "{release}"\n'
        f"#define HST_VERSION_BUILD {build}\n"
        f'#define HST_FILE_VERSION "{version}.{build}"\n#endif\n'
    )


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--version-file", type=pathlib.Path, default=ROOT / "VERSION")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--header", type=pathlib.Path)
    g.add_argument("--env", action="store_true")
    g.add_argument("--print", action="store_true", dest="show")
    g.add_argument("--release", action="store_true", dest="show_release")
    g.add_argument("--build", action="store_true", dest="show_build")
    ap.add_argument("--release-file", type=pathlib.Path, default=ROOT / "data" / "hst" / "release.json")
    a = ap.parse_args()
    version, parts = read_version(a.version_file)
    release = read_release(version, a.release_file)
    if a.show:
        print(version)
    elif a.show_release:
        print(release)
    elif a.show_build:
        print(release_build(release))
    elif a.env:
        for k, v in zip(("MAJOR", "MINOR", "MICRO"), parts):
            print(f"export HST_VERSION_{k}={int(v)}")
        print(f"export HST_VERSION={version}")
        print(f"export HST_RELEASE={release}")
        print(f"export HST_VERSION_BUILD={release_build(release)}")
    else:
        new = header_text(version, parts, release)
        if a.header.exists() and a.header.read_text(encoding="utf-8") == new:
            print(f"{a.header}: unchanged ({release})")
        else:
            a.header.parent.mkdir(parents=True, exist_ok=True)
            a.header.write_text(new, encoding="utf-8")
            print(f"{a.header}: written ({release})")


if __name__ == "__main__":
    main()
