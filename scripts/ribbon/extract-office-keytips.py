"""Ground truth of the familiar office suite's KeyTips and shortcuts, from captures on the Windows test PC.

Usage: python3 scripts/ribbon/extract-office-keytips.py RAW_DIR [WORD_KEYS_TSV] [--out data/ribbon/office-keytips-reference.json]

RAW_DIR holds the UI Automation dumps of the ribbon (one JSON list per app and tab, `<app>/<app>-w1920-NN-<tab>.json`,
`<app>/<app>-ctx-<kind>-1920-<tab>.json` and `<app>/<app>-keytips-1920.json`), entries {n: name, t: control type,
k: AccessKey such as "Alt, H, F F", help: tooltip}. They were taken on HST4 (Office 2021 LTSC 16.0.15601, en-US UI;
no vi-VN language pack is installed there) on 2026-11-14. WORD_KEYS_TSV is `KEY<TAB>Word command` from Word's
Application.FindKey for every Ctrl/Alt/Shift/F-key combination (the same machine and day). Excel and PowerPoint have no
such API: their shortcuts are the ones their tooltips name ("Bold (Ctrl+B)").
"""
import argparse
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "data", "ribbon", "office-keytips-reference.json")
APPS = ("word", "excel", "powerpoint")
# contextual tab dumps: file suffix -> tab name
CONTEXT = {"ctx-table-1920-table-design": "Table Design", "ctx-table-1920-layout": "Table Layout",
           "ctx-picture-1920-picture-format": "Picture Format", "ctx-chart-1920-chart-design": "Chart Design",
           "ctx-chart-1920-format": "Chart Format"}
SHORTCUT = re.compile(r"\(((?:Ctrl|Shift|Alt|F\d)[^)]*)\)\s*$")


def read(path):
    with open(path, encoding="utf-8-sig") as handle:
        return json.load(handle)


def keys_of(access_key):
    """'Alt, H, F F' -> ['H', 'FF']; '' -> []."""
    parts = [p.replace(" ", "") for p in access_key.split(", ")]
    return parts[1:] if parts and parts[0] == "Alt" else []


def tab_dumps(raw, app):
    """(tab name, path) of the dumps of one app at 1920 px: main tabs from their file name, contextual ones by kind."""
    for path in sorted(glob.glob(os.path.join(raw, app, f"{app}-w1920-*.json"))):
        slug = re.sub(r"^.*-w1920-\d\d-", "", os.path.basename(path))[:-5]
        yield slug.replace("-", " ").title().replace("Slide Show", "Slide Show"), path
    for suffix, tab in CONTEXT.items():
        path = os.path.join(raw, app, f"{app}-{suffix}.json")
        if os.path.exists(path):
            yield tab, path


def app_reference(raw, app):
    tabs, controls, groups, shortcuts = {}, {}, {}, {}
    for entry in read(os.path.join(raw, app, f"{app}-keytips-1920.json")):
        keys = keys_of(entry["k"])
        if entry["t"] == "TabItem" and len(keys) == 1:
            tabs[entry["n"]] = keys[0]
    for tab, path in tab_dumps(raw, app):
        rows, seen = [], set()
        for entry in read(path):
            keys = keys_of(entry["k"])
            tooltip = (entry.get("help") or "").split("\n")[0]
            found = SHORTCUT.search(tooltip)
            if found:
                shortcuts.setdefault(found.group(1), SHORTCUT.sub("", tooltip).strip())
            if len(keys) != 2 or entry["t"] in ("Pane", "TitleBar"):
                continue
            if entry["t"] == "Group":
                groups.setdefault(tab, []).append([entry["n"], keys[1]])
                continue
            name = entry["n"] if entry["n"] != "More Options" else None
            if name is None or (name, keys[1]) in seen:
                continue
            seen.add((name, keys[1]))
            rows.append([name, keys[1], SHORTCUT.sub("", tooltip).strip()])
        controls[tab] = rows
    return {"tabs": tabs, "controls": controls, "groups": groups, "tooltip_shortcuts": dict(sorted(shortcuts.items()))}


def word_keys(path):
    found = {}
    with open(path, encoding="utf-8-sig") as handle:
        for line in handle:
            key, _, command = line.rstrip("\n").partition("\t")
            if key and command.strip():
                found[key] = command.strip()
    return found


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("raw")
    parser.add_argument("word_keys", nargs="?")
    parser.add_argument("--out", default=OUT)
    args = parser.parse_args(argv)
    data = {"version": 1,
            "about": "KeyTips (UI Automation AccessKey) and shortcuts of the familiar office suite as installed on the "
                     "Windows test PC HST4: Office 2021 LTSC 16.0.15601, en-US UI (no Vietnamese UI installed, so the "
                     "English KeyTips are the reference). Generated by scripts/ribbon/extract-office-keytips.py; "
                     "controls: [name, KeyTip after the tab letter, tooltip without its shortcut].",
            "captured": "2026-11-14",
            "apps": {app: app_reference(args.raw, app) for app in APPS}}
    if args.word_keys:
        data["apps"]["word"]["findkey_shortcuts"] = word_keys(args.word_keys)
    text = json.dumps(data, ensure_ascii=False, indent=1)
    # one control per line keeps the file reviewable
    text = re.sub(r'\[\n\s+("[^"\n]*"),\n\s+("[^"\n]*"),\n\s+("[^"\n]*")\n\s+\]', r"[\1, \2, \3]", text)
    text = re.sub(r'\[\n\s+("[^"\n]*"),\n\s+("[^"\n]*")\n\s+\]', r"[\1, \2]", text)
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(text + "\n")
    counts = {app: sum(len(v) for v in d["controls"].values()) for app, d in data["apps"].items()}
    print(f"wrote {os.path.relpath(args.out, ROOT)}: controls {counts}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
