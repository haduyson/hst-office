"""Ribbon commands that get a tooltip, per app, read from a patched tree: data/ribbon/tooltip-inventory.json.

  python3 scripts/ribbon/ribbon-tooltip-inventory.py --src TREE [--write]   (TREE: fresh-applied source tree)

Per app (writer, calc, impress, draw): "main" = the commands of the tabs shown in every context (Home, Insert...,
not the File page), "contextual" = those found only on contextual tabs (table, picture, chart...), and
"ui_described" = the commands whose ribbon button already has an "hst-ribbon-description" line in the .ui, with that
line ("en", and "vi" from the patched Vietnamese .po), and "menu_described" = the same for the menu buttons without a
command ("Select ▾"), by object id: the builder shows that line under the button's label. Group launchers count as
commands. Without --write it only
compares the tree with the committed snapshot and exits 1 when they differ (the ribbon changed: regenerate, then
give the new commands a sentence in data/ribbon/tooltip-descriptions.json or list them under "except").
"""
import argparse
import json
import os
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
from office_parity_ui import ITEM_CLASSES, command_name, parse_notebookbar, read_po  # noqa: E402

SNAPSHOT = os.path.join(ROOT, "data", "ribbon", "tooltip-inventory.json")
MODULES = {"writer": ("swriter", "sw"), "calc": ("scalc", "sc"), "impress": ("simpress", "sd"), "draw": ("sdraw", "sd")}
# contexts of the tabs that are always there (Home lists the text contexts as well)
ALWAYS = {"default", "any", "Text", "DrawText", "TextObject"}
FILE_PAGES = {"FileLabel", "File"}


def key(command):
    """'.uno:Bold?x=1' -> '.uno:Bold'; other protocols stay whole ('org.hst.office.vi:ReportError')."""
    name = command_name(command)
    return name if name == command else ".uno:" + name


MENU_BUTTONS = ("svtlo-ManagedMenuButton", "GtkMenuButton")


def ui_descriptions(path, po_path):
    """({command: {"en", "vi"}} of the ribbon buttons with an hst-ribbon-description line, {object id: {"en", "vi"}}
    of the menu buttons without a command that have one)."""
    po = read_po(po_path) if os.path.exists(po_path) else {}
    found, menus = {}, {}
    for obj in ET.parse(path).getroot().iter("object"):
        if obj.get("class") not in ITEM_CLASSES + MENU_BUTTONS:
            continue
        props = {p.get("name"): p for p in obj.findall("property")}
        action, line = props.get("action-name"), props.get("hst-ribbon-description")
        if line is None or not line.text:
            continue
        text = {"en": line.text, "vi": po.get((line.get("context"), line.text), "")}
        if action is not None and action.text:
            found.setdefault(key(action.text), text)
        elif obj.get("class") in MENU_BUTTONS:
            menus[obj.get("id")] = text
    return found, menus


def inventory(src):
    apps = {}
    for app, (module, po) in MODULES.items():
        path = os.path.join(src, po, "uiconfig", module, "ui", "notebookbar.ui")
        main, contextual = set(), set()
        for page in parse_notebookbar(path):
            if page["id"] in FILE_PAGES or page["label"] in FILE_PAGES:
                continue
            commands = {key(".uno:" + c if ":" not in c else c) for c in page["commands"]}
            commands |= {key(".uno:" + l["command"] if ":" not in l["command"] else l["command"])
                         for l in page["launchers"]}
            (contextual if set(page["contexts"]) - ALWAYS else main).update(commands)
        described, menus = ui_descriptions(path, os.path.join(src, "translations", "source", "vi", po, "messages.po"))
        apps[app] = {"main": sorted(main), "contextual": sorted(contextual - main),
                     "ui_described": dict(sorted(described.items())), "menu_described": dict(sorted(menus.items()))}
    return {"about": "Generated by scripts/ribbon/ribbon-tooltip-inventory.py from a fresh-applied tree; do not edit.",
            "apps": apps}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--src", required=True)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    data = inventory(args.src)
    text = json.dumps(data, ensure_ascii=False, indent=1) + "\n"
    if args.write:
        with open(SNAPSHOT, "w", encoding="utf-8") as handle:
            handle.write(text)
        print(f"wrote {SNAPSHOT}")
        return 0
    with open(SNAPSHOT, encoding="utf-8") as handle:
        same = json.load(handle) == data
    print("inventory up to date" if same else "inventory differs from the tree: rerun with --write")
    return 0 if same else 1


if __name__ == "__main__":
    sys.exit(main())
