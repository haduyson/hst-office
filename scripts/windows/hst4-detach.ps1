<#
Run hst4-setup.ps1 / hst4-build.ps1 detached from the SSH session as a one-shot scheduled task
"hst-build-<Name>" under the current (admin) account: S4U logon (no stored password, no desktop),
highest privileges, normal priority, 3-day limit. The task deletes itself when the script ends;
output goes to <Root>\logs\task-<Name>.log.
  powershell -File hst4-detach.ps1 -Name build -Script D:\hst-build\tools\scripts\windows\hst4-build.ps1 -ScriptArgs '-Ref rc/1.0.2-batch1 -Jobs 28'
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][ValidatePattern('^[A-Za-z0-9-]{1,40}$')][string]$Name,
    [Parameter(Mandatory)][string]$Script,
    # Space-separated arguments for -Script (a single string so it survives `powershell -File`); no quotes or spaces inside values.
    [ValidatePattern('^[^"''`]*$')][string]$ScriptArgs = '',
    [string]$Root = 'D:\hst-build'
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$task = "hst-build-$Name"
if (-not (Test-Path -LiteralPath $Script -PathType Leaf)) { throw "script not found: $Script" }
$existing = Get-ScheduledTask -TaskName $task -ErrorAction SilentlyContinue
if ($existing) {
    if ($existing.State -eq 'Running') { throw "$task is already running" }
    Unregister-ScheduledTask -TaskName $task -Confirm:$false
}

function ConvertTo-Literal([string]$Value) { "'" + $Value.Replace("'", "''") + "'" }

# "-Switch" tokens stay bare so they bind as parameter names; every other value is a quoted literal.
$argText = (@($ScriptArgs -split '\s+' | Where-Object { $_ }) | ForEach-Object { if ($_ -match '^-[A-Za-z]+$') { $_ } else { ConvertTo-Literal $_ } }) -join ' '
$taskDir = Join-Path $Root 'tasks'
$logDir = Join-Path $Root 'logs'
New-Item -ItemType Directory -Force -Path $taskDir, $logDir | Out-Null
$runner = Join-Path $taskDir "$task.ps1"
$log = Join-Path $logDir "task-$Name.log"
@"
# Generated by hst4-detach.ps1; runs once, then removes its scheduled task.
`$ErrorActionPreference = 'Continue'
# Windows PowerShell 5.1 redirection writes UTF-16 unless Out-File's default encoding is set.
`$PSDefaultParameterValues['Out-File:Encoding'] = 'utf8'
`$rc = 1
try {
    "[`$(Get-Date -Format s)] start $task" | Out-File -LiteralPath $(ConvertTo-Literal $log) -Encoding utf8
    & $(ConvertTo-Literal $Script) $argText *>> $(ConvertTo-Literal $log)
    `$rc = if (`$?) { 0 } else { 1 }
} catch {
    "[`$(Get-Date -Format s)] ERROR `$_" | Out-File -LiteralPath $(ConvertTo-Literal $log) -Append -Encoding utf8
} finally {
    "[`$(Get-Date -Format s)] end $task rc=`$rc" | Out-File -LiteralPath $(ConvertTo-Literal $log) -Append -Encoding utf8
    Unregister-ScheduledTask -TaskName $(ConvertTo-Literal $task) -Confirm:`$false -ErrorAction SilentlyContinue
}
exit `$rc
"@ | Set-Content -LiteralPath $runner -Encoding utf8

$action = New-ScheduledTaskAction -Execute "$env:SystemRoot\System32\WindowsPowerShell\v1.0\powershell.exe" `
    -Argument "-NoProfile -NonInteractive -ExecutionPolicy Bypass -File `"$runner`"" -WorkingDirectory $Root
$principal = New-ScheduledTaskPrincipal -UserId ([Security.Principal.WindowsIdentity]::GetCurrent().Name) -LogonType S4U -RunLevel Highest
# Priority 4 = normal; Task Scheduler defaults to 7 (below normal), which would slow every compiler process.
$settings = New-ScheduledTaskSettingsSet -Priority 4 -ExecutionTimeLimit (New-TimeSpan -Days 3) -MultipleInstances IgnoreNew `
    -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable
Register-ScheduledTask -TaskName $task -Action $action -Principal $principal -Settings $settings `
    -Description 'HST Office local build (scripts/windows/hst4-detach.ps1); removes itself when done.' | Out-Null
Start-ScheduledTask -TaskName $task
Write-Output "started $task; log $log"
