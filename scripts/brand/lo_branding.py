"""Inputs for configure --with-branding: intro/about/logo/donate images and progress.conf."""
from PIL import Image, ImageDraw

from .common import png_bytes, render_text, svg_with_raster


def _rgb(hex_color):
    return tuple(int(hex_color[i:i + 2], 16) for i in (1, 3, 5))


def render_intro(spec, mark, scale):
    """Splash: white card, mark + wordmark, accent rule, progress area left clear."""
    cfg = spec["libreofficeBranding"]
    w, h = (v * scale for v in cfg["introSize"])
    img = Image.new("RGBA", (w, h), (255, 255, 255, 255))
    mh = round(cfg["introMarkHeight"] * scale)
    mw = round(mark.width * mh / mark.height)
    mx, my = round(cfg["introMarkPos"][0] * scale), round(cfg["introMarkPos"][1] * scale)
    img.alpha_composite(mark.resize((mw, mh), Image.LANCZOS), (mx, my))
    word = render_text(spec["newText"], spec["newText"]["text"], spec["newText"]["color"],
                       round(cfg["introWordHeight"] * scale))
    img.alpha_composite(word, (mx + mw + round(36 * scale), my + (mh - word.height) // 2))
    tag = render_text(spec["newText"], cfg["tagline"], cfg["taglineColor"], round(cfg["taglineHeight"] * scale))
    img.alpha_composite(tag, (w - tag.width - round(30 * scale), round(cfg["taglineY"] * scale)))
    ImageDraw.Draw(img).rectangle((0, h - round(6 * scale), w, h), fill=_rgb(spec["mark"]["color"]))
    return img


def render_lockup(spec, mark, word_color, bg=None):
    """Horizontal lockup at native mark size (mark pixels untouched), for logo*.svg."""
    cfg = spec["libreofficeBranding"]
    word = render_text(spec["newText"], spec["newText"]["text"], word_color, cfg["lockupWordHeight"])
    pad, gap = cfg["lockupPad"], cfg["lockupGap"]
    w = pad * 2 + mark.width + gap + word.width
    h = pad * 2 + mark.height
    img = Image.new("RGBA", (w, h), bg or (0, 0, 0, 0))
    img.alpha_composite(mark, (pad, pad))
    img.alpha_composite(word, (pad + mark.width + gap, pad + (mark.height - word.height) // 2))
    return img


def render_about(spec, logo):
    """Vertical native logo on a white rounded panel so it reads on light and dark dialogs."""
    pad = spec["libreofficeBranding"]["aboutPad"]
    w, h = logo.width + 2 * pad, logo.height + 2 * pad
    big = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    ImageDraw.Draw(big).rounded_rectangle((0, 0, w - 1, h - 1), radius=pad, fill=(255, 255, 255, 255))
    big.alpha_composite(logo, (pad, pad))
    return big


def render_donate(spec, mark, size, opaque):
    img = Image.new("RGBA", (size, size), (255, 255, 255, 255) if opaque else (0, 0, 0, 0))
    side = round(size * 0.7)
    w = side
    h = round(mark.height * side / mark.width)
    img.alpha_composite(mark.resize((w, h), Image.LANCZOS), ((size - w) // 2, (size - h) // 2))
    return img.convert("RGB") if opaque else img


def progress_conf(spec):
    p = spec["libreofficeBranding"]["progress"]
    lines = ["# Sourced by LibreOffice configure (--with-branding). Positions are for intro.png.",
             "# Generated by scripts/generate-brand-assets.py; do not edit."]
    lines += [f'{key}="{value}"' for key, value in sorted(p.items())]
    return ("\n".join(lines) + "\n").encode("utf-8")


def build_lo_branding(spec, mark, logo):
    cfg = spec["libreofficeBranding"]
    out_dir = cfg["dir"]
    dark = cfg["darkWordColor"]
    out = {
        "intro.png": png_bytes(render_intro(spec, mark, 1)),
        "intro-highres.png": png_bytes(render_intro(spec, mark, 2)),
        "donate1.png": png_bytes(render_donate(spec, mark, 200, True)),
        "donate2.png": png_bytes(render_donate(spec, mark, 150, False)),
        "progress.conf": progress_conf(spec),
    }
    about = render_about(spec, logo)
    out["about.svg"] = svg_with_raster(png_bytes(about), about.width, about.height, "HST Office")
    for stem, color in (("logo", spec["newText"]["color"]), ("logo_inverted", dark),
                        ("logo-sc", spec["newText"]["color"]), ("logo-sc_inverted", dark)):
        lock = render_lockup(spec, mark, color)
        out[stem + ".svg"] = svg_with_raster(png_bytes(lock), lock.width, lock.height, "HST Office")
    return {f"{out_dir}/{name}": data for name, data in out.items()}
