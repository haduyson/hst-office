"""Draw the Cổ điển "clear formatting" icons: Colibre's letter A and baseline with a WHITE eraser.

  python3 scripts/brand/draw-hst-classic-eraser.py --tree <libreoffice-src> [--check]

Colibre draws .uno:ResetAttributes (and .uno:SetDefault, linked to it) as an "A" with a red eraser.
White reads as "wiped clean" (owner decision of 21/11/2026), so the Cổ điển overlay replaces the
three sizes (sc_ 16 px, lc_ 24 px, 32/ 32 px) for light and dark with these files. The letter and
the baseline stay Colibre's own paths (CC0 1.0), copied from the tree; only the eraser is new
HST geometry: a rectangle tilted 45 degrees at Colibre's place and size, its tip end rounded.
  light: white body, outline and sleeve line in Colibre's ink #3A3A38 (visible on white menus);
  dark:  solid #FAFAFA body, the sleeve line cut out so the dark menu shows through.
Writes icon-themes-src/hst-classic/{light,dark}/cmd/...; --check fails when they are stale.
"""
import argparse
import math
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "icon-themes-src/hst-classic"
R2 = math.sqrt(2)
INK = {"light": "#3a3a38", "dark": "#fafafa"}
COLIBRE = {"light": "colibre_svg", "dark": "colibre_dark_svg"}
# name -> (canvas, eraser band x+y, band y-x (top end, tip end), sleeve line at y-x, pen px, tip radius px)
# The bands follow Colibre's red eraser of the same size, so the composition does not move.
ERASERS = {
    "cmd/sc_resetattributes.svg": (16, (18.0, 24.6), (-7.0, 6.2), 2.4, 1.2, 0.8),
    "cmd/lc_resetattributes.svg": (24, (29.6, 37.2), (-6.2, 9.0), 3.4, 1.15, 1.0),
    "cmd/32/resetattributes.svg": (32, (37.9, 46.3), (-7.8, 10.2), 3.6, 1.15, 1.2),
}
RED = re.compile(r'<g fill="#(?:ed3d3b|d42314|ff9198)"[^>]*>.*?</g>|<path[^>]*fill="#(?:d42314|ff9198)"[^>]*/>')


def _num(value):
    return f"{value:.3f}".rstrip("0").rstrip(".")


def _xy(s, d):
    """Canvas point of band coordinates s = x + y, d = y - x."""
    return f"{_num((s - d) / 2)} {_num((s + d) / 2)}"


def tilted(s0, s1, d0, d1, radius=0.0):
    """Path of the 45-degree rectangle s0..s1 x d0..d1; the two corners at d1 rounded by radius px."""
    if radius <= 0:
        return f"M{_xy(s0, d0)} L{_xy(s1, d0)} L{_xy(s1, d1)} L{_xy(s0, d1)} Z"
    r, step = _num(radius), radius * R2
    return (f"M{_xy(s0, d0)} L{_xy(s1, d0)} L{_xy(s1, d1 - step)} A{r} {r} 0 0 1 {_xy(s1 - step, d1)} "
            f"L{_xy(s0 + step, d1)} A{r} {r} 0 0 1 {_xy(s0, d1 - step)} Z")


def eraser(mode, spec):
    _, (s0, s1), (d0, d1), sleeve, pen, radius = spec
    t = pen * R2  # a pen of `pen` px across a 45-degree edge spans pen * sqrt(2) band units
    if mode == "dark":
        return (f'<path d="{tilted(s0, s1, d0, sleeve - t / 2)}" fill="#fafafa"/>'
                f'<path d="{tilted(s0, s1, sleeve + t / 2, d1, radius)}" fill="#fafafa"/>')
    outer = tilted(s0, s1, d0, d1, radius)
    inner = tilted(s0 + t, s1 - t, d0 + t, d1 - t, max(radius - pen, 0))
    return (f'<path d="{outer}" fill="#ffffff"/>'
            f'<path d="{outer} {inner}" fill="{INK[mode]}" fill-rule="evenodd"/>'
            f'<path d="{tilted(s0, s1, sleeve - t / 2, sleeve + t / 2)}" fill="{INK[mode]}"/>')


def draw(tree, mode, name):
    spec = ERASERS[name]
    colibre = (tree / "icon-themes" / COLIBRE[mode] / name).read_text(encoding="utf-8").strip()
    body, count = RED.subn("", re.sub(r"^<svg[^>]*>|</svg>$", "", colibre))
    if count == 0 or re.search(r"#(?:ed3d3b|d42314|ff9198)", body, re.I):
        raise ValueError(f"{COLIBRE[mode]}/{name}: Colibre's red eraser not found as expected; re-audit")
    size = spec[0]
    return (f'<svg viewBox="0 0 {size} {size}" xmlns="http://www.w3.org/2000/svg">'
            "<!-- HST Office Cổ điển. Letter A and baseline: LibreOffice Colibre, CC0 1.0. "
            "White eraser: HASON TECH, CC-BY-4.0. Generated by scripts/brand/draw-hst-classic-eraser.py -->"
            f"{body}{eraser(mode, spec)}</svg>\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--tree", type=Path, required=True, help="LibreOffice source tree (its Colibre)")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for mode in INK:
        for name in ERASERS:
            path, text = OUT / mode / name, draw(args.tree, mode, name)
            if args.check:
                if not path.is_file() or path.read_text(encoding="utf-8") != text:
                    stale.append(str(path.relative_to(ROOT)))
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if stale:
        print("stale, rerun without --check: " + " ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
