"""Overwrite upstream application/document icons in a LibreOffice source tree with HST ones.

  python3 scripts/brand/apply-icon-overrides.py --tree <libreoffice-src> [--check]

Targets (all generated by scripts/generate-brand-assets.py, committed under branding/):
- sysui/desktop/icons/{soffice,writer_app,calc_app,impress_app,draw_app,math_app,base_app}.ico
  <- branding/windows/app-icons/ (Windows exe, shortcut, taskbar and Programs and Features icon);
- icon-themes/*/res/mainapp_<size>[_8].{png,svg} <- branding/icon-themes/mainapp-<size>.{png,svg}
  (window / Start Center icon, every theme incl. dark and SVG variants, all platforms);
- document-type icons listed in branding/doc-icons/overrides.json when that file exists.
Idempotent. Exits 1 when an expected target is missing from the tree, and (also with --check
alone) when any target still carries bytes listed in branding/icon-themes/upstream-sha256.json.
"""
import argparse
import glob
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
APP_ICONS = os.path.join(ROOT, "branding", "windows", "app-icons")
THEME_DIR = os.path.join(ROOT, "branding", "icon-themes")
UPSTREAM_HASHES = os.path.join(THEME_DIR, "upstream-sha256.json")
DOC_OVERRIDES = os.path.join(ROOT, "branding", "doc-icons", "overrides.json")
SYSUI_ICONS = ["soffice.ico", "writer_app.ico", "calc_app.ico", "impress_app.ico",
               "draw_app.ico", "math_app.ico", "base_app.ico"]
MAINAPP = re.compile(r"^mainapp_(\d+)(?:_8)?\.(png|svg)$")
THEME_SIZES = (16, 24, 32, 48)


def nearest(size):
    return min(THEME_SIZES, key=lambda s: (abs(s - size), -s))


def plan(tree):
    """Return ([(source, target)], [missing target descriptions])."""
    pairs, missing = [], []
    for name in SYSUI_ICONS:
        target = os.path.join(tree, "sysui", "desktop", "icons", name)
        if not os.path.isfile(target):
            missing.append(target)
        pairs.append((os.path.join(APP_ICONS, name), target))
    themes = sorted(d for d in glob.glob(os.path.join(tree, "icon-themes", "*")) if os.path.isdir(d))
    if not themes:
        missing.append(os.path.join(tree, "icon-themes", "*"))
    for theme in themes:
        found = 0
        for path in sorted(glob.glob(os.path.join(theme, "res", "mainapp_*"))):
            match = MAINAPP.match(os.path.basename(path))
            if not match:
                continue
            found += 1
            size, ext = nearest(int(match.group(1))), match.group(2)
            pairs.append((os.path.join(THEME_DIR, f"mainapp-{size}.{ext}"), path))
        if not found:
            missing.append(os.path.join(theme, "res", "mainapp_*"))
    if os.path.isfile(DOC_OVERRIDES):
        with open(DOC_OVERRIDES, encoding="utf-8") as handle:
            doc = json.load(handle)
        for rel_target, rel_source in sorted(doc["files"].items()):
            targets = sorted(glob.glob(os.path.join(tree, rel_target)))
            if not targets:
                missing.append(os.path.join(tree, rel_target))
            for target in targets:
                pairs.append((os.path.join(ROOT, rel_source), target))
    return pairs, missing


def sha256(path):
    with open(path, "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tree", required=True, help="LibreOffice source tree")
    parser.add_argument("--check", action="store_true", help="only verify, do not copy")
    args = parser.parse_args()
    pairs, missing = plan(os.path.abspath(args.tree))
    for path in missing:
        print(f"error: expected icon target missing: {path}")
    absent_sources = sorted({src for src, _ in pairs if not os.path.isfile(src)})
    for src in absent_sources:
        print(f"error: HST icon source missing (run scripts/generate-brand-assets.py): {src}")
    if missing or absent_sources:
        return 1
    copied = 0
    if not args.check:
        for src, dst in pairs:
            with open(src, "rb") as handle:
                data = handle.read()
            if os.path.isfile(dst):
                with open(dst, "rb") as handle:
                    if handle.read() == data:
                        continue
            with open(dst, "wb") as handle:
                handle.write(data)
            copied += 1
    with open(UPSTREAM_HASHES, encoding="utf-8") as handle:
        upstream = set(json.load(handle)["sha256"])
    leftover = [dst for _, dst in pairs if sha256(dst) in upstream]
    for dst in leftover:
        print(f"error: upstream icon bytes still present: {dst}")
    print(f"icon overrides: {len(pairs)} targets, {copied} updated, {len(leftover)} upstream left")
    return 1 if leftover else 0


if __name__ == "__main__":
    sys.exit(main())
