"""Write hst-ribbon-adaptive-ladders.patch: the step orders of data/ribbon/adaptive-ladders.json in the ladders.

Usage: scripts/patches/generate-ribbon-adaptive-ladders.py --tree DIR [--check]

DIR is a LibreOffice tree with the series applied up to the patch before this one (a fresh-apply tree of
the branch before hst-ribbon-adaptive-ladders.patch was added). Each named tab must have a ladder in vcl/inc/HstRibbonLadders.hxx and every step must name one of
its groups with a state M, S or C; any mismatch fails loudly. The output is byte-stable.
"""
import argparse
import difflib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HEADER = "vcl/inc/HstRibbonLadders.hxx"
OUT = os.path.join(ROOT, "patches/libreoffice/hst-ribbon-adaptive-ladders.patch")
STATES = {"M": 1, "S": 2, "C": 3}
DESCRIPTION = """HST Office: ribbon tabs scale in the approved 1.0.2 order, keeping labels longest (generated).

Generated by scripts/patches/generate-ribbon-adaptive-ladders.py from data/ribbon/adaptive-ladders.json.
Owner decisions 14/11/2026: a group goes from large to medium (small icons with labels in an even 3-row
grid), then to small (icons only), and only then becomes its "Caption ▾" button, one group per step, in a
fixed order per tab: Writer's Home shrinks its Styles gallery first and collapses Font last; Insert keeps
its labels at 1366 px. The other tabs keep the usage-based order of hst-ribbon-scale-ladders-ux.patch.

"""


class LadderError(Exception):
    pass


def replaced(text, data):
    for ladder in data["ladders"]:
        name = f"{ladder['app']}_{re.sub(r'\W', '_', ladder['box'])}"
        groups = re.search(rf"^inline constexpr std::u16string_view {name}_groups\[\] = \{{ (.*) \}};$", text, re.M)
        if not groups:
            raise LadderError(f"no ladder {name} in {HEADER}")
        known = re.findall(r'u"([^"]+)"', groups.group(1))
        for group, state in ladder["steps"]:
            if group not in known or state not in STATES:
                raise LadderError(f"{name}: bad step {group!r} {state!r} (groups: {known})")
        steps = ", ".join(f'{{ u"{g}", {STATES[s]} }}' for g, s in ladder["steps"])
        line = f"inline constexpr Step {name}_steps[] = {{ {steps} }};"
        text, count = re.subn(rf"^inline constexpr Step {name}_steps\[\] = .*;$", lambda _m: line, text, flags=re.M)
        if count != 1:
            raise LadderError(f"no steps of {name} in {HEADER}")
    return text


def patch_text(tree, data):
    old = open(os.path.join(tree, HEADER), encoding="utf-8").read()
    new = replaced(old, data)
    body = "".join(difflib.unified_diff(old.splitlines(keepends=True), new.splitlines(keepends=True),
                                        fromfile=f"a/{HEADER}", tofile=f"b/{HEADER}", n=3))
    if not body:
        raise LadderError("the data does not change the ladders")
    return DESCRIPTION + body


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tree", required=True)
    parser.add_argument("--data", default=os.path.join(ROOT, "data/ribbon/adaptive-ladders.json"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = json.load(open(args.data, encoding="utf-8"))
    try:
        text = patch_text(args.tree, data)
    except LadderError as error:
        print(f"adaptive ladders do not match the ribbon: {error}", file=sys.stderr)
        return 2
    if args.check:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        print("up to date" if current == text else f"{os.path.relpath(OUT, ROOT)} is out of date")
        return 0 if current == text else 1
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
