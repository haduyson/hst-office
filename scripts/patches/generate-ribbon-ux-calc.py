"""Generate the HST Sheets part of the ribbon UX rework (patches/libreoffice/hst-ribbon-ux-calc.patch).

Usage: scripts/patches/generate-ribbon-ux-calc.py --tree DIR [--out PATCH] [--check]

DIR is a LibreOffice tree with the series applied up to (not including) this patch. The generator edits the
Tabbed notebookbar.ui of Calc (audit 13/11, section 4; owner decisions of 13/11) and writes one patch with the
.ui, the Vietnamese strings (sc/messages.po) and the gla11y lines (scalc.suppr). Data: ribbon_ux_calc_data.py.

- Every group body has two rows; drop-down buttons (svtlo-ManagedMenuButton with a GtkMenu of commands) replace
  rows of unlabelled icons; the trailing "<tab> ▾" blocks go (the Extension tab keeps its add-on menus block).
- Ribbon-only labels and the tooltips' second lines are the translatable properties hst-ribbon-label and
  hst-ribbon-description (hst-ribbon-ux-engine.patch); menus, the menu bar and the feature search keep the
  command labels.
- Every command that leaves the ribbon stays in the menu bar.
The output is byte-stable; --check only compares it with the existing patch.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ribbon_ux_lib as L  # noqa: E402
import ribbon_ux_calc_tabs as tabs  # noqa: E402
from ribbon_ux_calc_builder import Builder  # noqa: E402
from ribbon_ux_calc_data import DROP_BLOCKS, PO_ANCHOR, SUPPR, UI, VI_PO  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MENU_ITEMS = ("GtkMenuItem", "GtkCheckMenuItem", "GtkRadioMenuItem")
OUT = os.path.join(ROOT, "patches", "libreoffice", "hst-ribbon-ux-calc.patch")
DESCRIPTION = """HST Office: HST Sheets ribbon UX rework (generated).

Generated by scripts/patches/generate-ribbon-ux-calc.py (data: scripts/patches/ribbon_ux_calc_data.py) from
the Tabbed notebookbar.ui of Calc, after the audit of 13/11 and the owner decisions of 13/11:
- Home: Editing group = AutoSum (split button), Fill ▾, Clear ▾, Sort and Filter ▾, Find and Select ▾; the Tools block goes;
  Wrap Text and Merge and Center (split button) are labelled; Cells = Insert ▾, Delete ▾, Format ▾; Conditional Formatting
  and Format as Table labelled; the đồng (₫) and dd/mm/yyyy formats of the HST extension in the Number group.
- Insert: Pivot Table and Table (refresh/delete pivot table are on the Pivot Table contextual tab); one
  Shapes ▾; Column, Line and Pie chart buttons; no Extensions group.
- Page Layout: Margins ▾, Orientation ▾, Size ▾ (Calc's page-style commands CalcPageMargin, Orientation,
  CalcPageSize), Print Area ▾, Breaks ▾, Header and Footer, Fit All Columns on One Page.
  The split buttons, the chart types and Fit All Columns need hst-ribbon-ux-calc-commands.patch.
- Formulas: Insert Function, AutoSum (split button), Function List, six function categories ▾ (InsertFunction, as the
  sidebar's function list), Number to Words (DOCTIEN); names and auditing labels; no Fill Mode.
- Data: From Text/CSV and Other Sources ▾; Sort and Filter, Data Tools (with Convert to Number of
  hst-sheets-text-to-number.patch), What-If Analysis, Group and Subtotal; no Shuffle.
- Review: Protect Sheet, Protect Workbook, Track Changes, Accept or Reject; no Hyphenation.
- View: Freeze Panes ▾ (split button) always in the Window group; Normal; Gridlines; no Macros group.
- Extension: Vietnamese utility groups first (with Convert to Unicode), the other HST groups, then one
  Developer group (macros, controls, XML source).
- Contextual: Assign Macro last; "Fill and Border".
The trailing "<tab> ▾" blocks go, except the Extension tab's add-on menus block. Every command that leaves the
ribbon stays in the menu bar and the feature search (Alt+Q)."""


def build(text):
    b = Builder(text)
    for tab in (tabs.home, tabs.insert, tabs.page_layout, tabs.formulas, tabs.data, tabs.review, tabs.view,
                tabs.extension, tabs.contextual):
        tab(b)
    b.drop(*DROP_BLOCKS)  # after the tabs took the blocks' last commands
    b.apply_strings()
    L.check_unique(b.root)
    return b


def unlabelled_items(root):
    """(class, id) of the tool buttons and menu items without a label property (gla11y button-no-label)."""
    return [(o.get("class"), o.get("id")) for o in root.iter("object")
            if o.get("class") in L.BUTTON_CLASSES + MENU_ITEMS and o.get("id")
            and not any(p.get("name") == "label" for p in o.findall("property"))]


def suppr_update(text, old_root, root):
    """scalc.suppr with the button-no-label lines of the items this patch changes, changing as few lines as
    possible (ribbon_ux_lib.suppr() rewrites them all and knows only tool buttons, not menu items): lines of
    items that were unlabelled before and are gone or labelled now go; lines of new unlabelled items follow
    the file's last line of notebookbar.ui; lines of other patches stay as they are."""
    def line(klass, oid):
        return f"{UI}://{klass}[@id='{oid}'] button-no-label\n"
    before = {line(k, i) for k, i in unlabelled_items(old_root)}
    wanted = [line(k, i) for k, i in unlabelled_items(root)]
    kept = [x for x in text.splitlines(keepends=True) if x not in before or x in set(wanted)]
    new = [x for x in wanted if x not in set(kept)]
    last = max((n for n, x in enumerate(kept) if x.startswith(UI + ":")), default=len(kept) - 1)
    return "".join(kept[:last + 1] + new + kept[last + 1:])


def patch_text(tree):
    old_ui = L.read(tree, UI)
    b = build(old_ui)
    new_ui = L.serialize_like(old_ui, b.root)
    old_po = L.read(tree, VI_PO)
    new_po = L.po_with_entries(old_po, UI, b.strings, PO_ANCHOR)
    old_suppr = L.read(tree, SUPPR)
    new_suppr = suppr_update(old_suppr, L.parse_text(old_ui), b.root)
    return [L.file_diff(UI, old_ui, new_ui), L.file_diff(VI_PO, old_po, new_po),
            L.file_diff(SUPPR, old_suppr, new_suppr)]


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tree", required=True)
    parser.add_argument("--out", default=OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        diffs = patch_text(args.tree)
    except (L.RibbonUxError, OSError, StopIteration, KeyError, ValueError) as error:
        print(f"cannot generate the Sheets ribbon: {error!r}", file=sys.stderr)
        return 2
    return L.write_patch(args.out, DESCRIPTION, diffs, check=args.check)


if __name__ == "__main__":
    sys.exit(main())
