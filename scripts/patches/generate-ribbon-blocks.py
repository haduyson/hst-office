"""Generate the bare-button rung of the tabs' right-hand blocks (vcl/inc/HstRibbonBlocks.hxx) as one patch.

Usage: scripts/patches/generate-ribbon-blocks.py --tree DIR [--data data/ribbon/scaling-ladders.json]
           [--out patches/libreoffice/hst-ribbon-tools-bare-ladders.patch] [--check]

A ladder of data/ribbon/scaling-ladders.json may name "bare_block_before": a group of its merged box that
collapses into its button (a "C" step). The block beside the box (the Home tab's Tools, already shown as its
captioned button) then drops its caption and shows a bare arrow when that alone keeps the group from
collapsing, and only then. The ladders are checked against the ribbon content exactly as
generate-ribbon-scale.py does; the output is byte-stable; --check only compares it with the existing patch.
"""
import argparse
import importlib.util
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
_spec = importlib.util.spec_from_file_location("generate_ribbon_scale", os.path.join(os.path.dirname(__file__), "generate-ribbon-scale.py"))
scale = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(scale)

HEADER = "vcl/inc/HstRibbonBlocks.hxx"
STAGES = {"draw": "hst-ribbon-tools-bare-draw.patch"}
FOLLOW_UPS = {"draw": """HST Office: HST Draw's Tools button drops its caption before Paragraph collapses (generated).

Generated by scripts/patches/generate-ribbon-blocks.py --since draw from data/ribbon/scaling-ladders.json and
checked against the ribbon content of the four Tabbed notebookbar.ui files. Adds HST Draw's Home tab
(hst-ribbon-draw.patch) to vcl/inc/HstRibbonBlocks.hxx, as Slides has it.

"""}
DESCRIPTION = """HST Office: the Home tab's Tools button drops its caption before Paragraph collapses (generated).

Generated by scripts/patches/generate-ribbon-blocks.py from data/ribbon/scaling-ladders.json and checked
against the ribbon content of the three Tabbed notebookbar.ui files. vcl/inc/HstRibbonBlocks.hxx (new)
names, per merged group box, the group whose collapse into its button the right-hand block (Tools) prevents
by showing a bare arrow instead of its caption; hst-ribbon-tools-bare.patch uses it.

"""


def validate(data, tree):
    scale.validate(data, tree)
    for ladder in data["ladders"]:
        group = ladder.get("bare_block_before")
        if group is None:
            continue
        if [group, "C"] not in ladder["steps"]:
            raise scale.LadderError(f"{ladder['app']}/{ladder['box']}: bare_block_before {group!r} has no C step")


def header(data):
    lines = ["/* -*- Mode: C++; tab-width: 4; indent-tabs-mode: nil; c-basic-offset: 4 -*- */",
             "/*", " * This file is part of the LibreOffice project.", " *",
             " * This Source Code Form is subject to the terms of the Mozilla Public",
             " * License, v. 2.0. If a copy of the MPL was not distributed with this",
             " * file, You can obtain one at http://mozilla.org/MPL/2.0/.", " */", "",
             "#pragma once", "",
             "// HST Office: the bare-button rung of the tabs' right-hand blocks. GENERATED by",
             "// scripts/patches/generate-ribbon-blocks.py from data/ribbon/scaling-ladders.json; do not edit.", "",
             "#include <cstddef>", "#include <iterator>", "#include <string_view>", "", "namespace hst::ribbon::blocks", "{",
             "struct Block", "{", "    const std::u16string_view* groups; // the merged box's groups, visual order",
             "    std::size_t groupCount;",
             "    std::u16string_view bareBefore; // the block goes bare rather than let this group collapse", "};", ""]
    entries = []
    for ladder in data["ladders"]:
        if "bare_block_before" not in ladder:
            continue
        name = f"{ladder['app']}_{ladder['box']}"
        ids = ", ".join(f'u"{g}"' for g in ladder["groups"])
        lines.append(f"// {ladder['app']}: {ladder['box']}")
        lines.append(f"inline constexpr std::u16string_view {name}_groups[] = {{ {ids} }};")
        lines.append("")
        entries.append(f'    {{ {name}_groups, std::size({name}_groups), u"{ladder["bare_block_before"]}" }},')
    lines += ["inline constexpr Block all[] = {", *entries, "};", "}", "",
              "/* vim:set shiftwidth=4 softtabstop=4 expandtab: */"]
    return "\n".join(lines) + "\n"


def patch_text(content):
    body = content.splitlines()
    out = [DESCRIPTION.rstrip("\n"), "", "--- /dev/null", f"+++ b/{HEADER}", f"@@ -0,0 +1,{len(body)} @@"]
    out += ["+" + line for line in body]
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tree", required=True)
    parser.add_argument("--data", default=os.path.join(ROOT, "data/ribbon/scaling-ladders.json"))
    parser.add_argument("--out", default=os.path.join(ROOT, "patches/libreoffice/hst-ribbon-tools-bare-ladders.patch"))
    parser.add_argument("--since", choices=sorted(STAGES),
                        help="write the follow-up patch of this stage (default --out: its patch in patches/libreoffice)")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with open(args.data, encoding="utf-8") as handle:
        data = json.load(handle)
    try:
        validate(data, args.tree)
        if args.since:
            if args.out == parser.get_default("out"):
                args.out = os.path.join(ROOT, "patches/libreoffice", STAGES[args.since])
            text = scale.follow_up_text(header(scale.stage(data)), header(scale.stage(data, args.since)),
                                        FOLLOW_UPS[args.since], HEADER)
        else:
            text = patch_text(header(scale.stage(data)))
    except scale.LadderError as error:
        print(f"ladder data does not match the ribbon content: {error}", file=sys.stderr)
        return 2
    if args.check:
        current = open(args.out, encoding="utf-8").read() if os.path.exists(args.out) else ""
        if current != text:
            print(f"{os.path.relpath(args.out, ROOT)} is out of date", file=sys.stderr)
            return 1
        print("up to date")
        return 0
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"wrote {os.path.relpath(args.out, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
