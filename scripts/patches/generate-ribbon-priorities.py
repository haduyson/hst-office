"""Generate the collapse ladders of every ribbon tab from group priorities (hst-ribbon-scale-ladders-ux.patch).

Usage: scripts/patches/generate-ribbon-priorities.py --tree DIR [--data data/ribbon/scaling-priorities.json]
           [--out patches/libreoffice/hst-ribbon-scale-ladders-ux.patch] [--check]

The ribbon UX audit of 13/11/2026 asked for a collapse order by usage on every tab, not only Home. Each
entry of the data names a merged group box, its groups in visual order and their priority (most used
first). The ladder written for it shrinks the least used groups first, one state at a time across the
row (every group to medium, then to small, then into its "Caption ▾" button), and folds them first; the
engine lays a fitting row out again from the same priority (hst::ribbon::fitByPriority,
hst-ribbon-ux-engine.patch), so only the least used groups ever become buttons.

The patch replaces vcl/inc/HstRibbonLadders.hxx as left by generate-ribbon-scale.py (its committed patches,
up to the Draw stage) with the ladders of this data only: the tabs were reworked after those ladders, so
they would no longer match. DIR is a LibreOffice tree with the whole series applied up to this patch; every
entry is checked against it (generate-ribbon-scale.validate), so a content change never silently disables
a ladder. The output is byte-stable; --check only compares it with the existing patch.
"""
import argparse
import importlib.util
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
_spec = importlib.util.spec_from_file_location("generate_ribbon_scale", os.path.join(ROOT, "scripts/patches/generate-ribbon-scale.py"))
scale = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(scale)

DATA = os.path.join(ROOT, "data/ribbon/scaling-priorities.json")
OUT = os.path.join(ROOT, "patches/libreoffice/hst-ribbon-scale-ladders-ux.patch")
DESCRIPTION = """HST Office: collapse ladders of every ribbon tab, by usage (generated).

Generated by scripts/patches/generate-ribbon-priorities.py from data/ribbon/scaling-priorities.json and
checked against the reworked ribbon content of the four Tabbed notebookbar.ui files. Replaces the
ladders of vcl/inc/HstRibbonLadders.hxx (Home tabs only, from scaling-ladders.json) with one ladder per
tab: the least used groups shrink, then become their "Caption ▾" button, then fold first; the most used
groups (Clipboard, Font, Freeze Panes, Track Changes...) stay open longest.

"""


class PriorityError(Exception):
    pass


def ladders(data):
    """The scaling-ladders.json form of the priority data: steps M, S, C least used first; fold the same."""
    out = []
    for entry in data["ladders"]:
        groups, priority = entry["groups"], entry["priority"]
        if sorted(priority) != sorted(groups) or len(set(priority)) != len(priority):
            raise PriorityError(f"{entry['app']}/{entry['box']}: the priority must name every group exactly once")
        keep_open = set(entry.get("keep_open", []))
        if not keep_open <= set(groups):
            raise PriorityError(f"{entry['app']}/{entry['box']}: keep_open names unknown groups")
        least_first = list(reversed(priority))
        # a nested add-on box folds whole and never becomes a "Caption ▾" button
        steps = [[g, state] for state in ("M", "S", "C") for g in least_first if state != "C" or g not in keep_open]
        out.append({"app": entry["app"], "box": entry["box"], "groups": groups, "steps": steps, "fold": least_first})
    return {"ladders": out}


def patch_text(data):
    with open(os.path.join(ROOT, "data/ribbon/scaling-ladders.json"), encoding="utf-8") as handle:
        old_data = json.load(handle)
    old = scale.header(scale.stage(old_data, "draw"))
    named = ladders(data)
    for ladder in named["ladders"]:  # the box id only names the C++ arrays ("pmhbDesign Tab")
        ladder["box"] = re.sub(r"\W", "_", ladder["box"])
    return scale.follow_up_text(old, scale.header(named), DESCRIPTION)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tree", required=True)
    parser.add_argument("--data", default=DATA)
    parser.add_argument("--out", default=OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with open(args.data, encoding="utf-8") as handle:
        data = json.load(handle)
    try:
        converted = ladders(data)
        scale.validate(converted, args.tree)
        text = patch_text(data)
    except (PriorityError, scale.LadderError) as error:
        print(f"priority data does not match the ribbon content: {error}", file=sys.stderr)
        return 2
    if args.check:
        current = open(args.out, encoding="utf-8").read() if os.path.exists(args.out) else ""
        if current != text:
            print(f"{os.path.relpath(args.out, ROOT)} is out of date", file=sys.stderr)
            return 1
        print("up to date")
        return 0
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"wrote {os.path.relpath(args.out, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
