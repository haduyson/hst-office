"""Direction A: Home captions, horizontal breathing room and two icon-only buttons, without regrouping.

Generate against a source tree with the preceding series already applied:
  python3 scripts/patches/generate-ribbon-look.py --tree TREE --patch FILE
For sandbox validation only, --installed DIR edits the copied installation's UI.
The ID-based edits preserve XML formatting, commands, order, priorities and heights.
"""
import argparse
import difflib
from pathlib import Path
import re
import xml.etree.ElementTree as ET

APPS = (("sw", "swriter"), ("sc", "scalc"), ("sd", "simpress"))
# Toolboxes of Home shown as icons only; every app must have exactly two.
ICON_ONLY = ("bxHomeFormatPaintbrush", "bxHomeResetAttributes", "bxHomeSetDefaults")
HEADER = """HST Office: direction A, resource phase, Home only.

Generated by scripts/patches/generate-ribbon-look.py against the preceding series.
Re-run after the contextual-tab/fold changes; do not hand-merge large XML blocks.
Upright group captions retain their translations and scale. Move one horizontal
margin pixel from end to start and increase existing column gaps by one pixel.
Clone Formatting and Clear on Home become icon-only, as they do at 1366 px in Office:
Sheets' Number and Slides' Paragraph then fit next to the banner. Their commands keep
the tooltips and the accessible names, which come from the command labels.
No widget moves, command/priority changes, vertical metric changes or VCL paint.
License: upstream UI files remain MPL-2.0.
---
"""


def transform(text):
    root = ET.fromstring(text)
    parents = {child: parent for parent in root.iter() for child in parent}
    label = root.find('.//object[@id="HomeLabel"]')
    tab = parents[label]
    siblings = list(parents[tab])
    home = siblings[siblings.index(tab) - 1]
    ids = {o.get("id"): o.get("class") for o in home.iter("object") if o.get("id")}
    stack, spans = [], {}
    for token in re.finditer(r'<object\b[^>]*>|</object>', text):
        if token.group().startswith("</"):
            start, ident = stack.pop()
            spans[ident] = (start, token.end())
        else:
            match = re.search(r'\bid="([^"]+)"', token.group())
            ident = match.group(1) if match else None
            if token.group().endswith("/>"):
                spans[ident] = (token.start(), token.end())
            else:
                stack.append((token.start(), ident))
    edits = []
    icon_only = 0
    for ident, klass in ids.items():
        if not (ident.startswith("lbHome") or ident.startswith("gdHome") or ident in ICON_ONLY):
            continue
        start, end = spans[ident]
        old = text[start:end]
        new = old
        if ident in ICON_ONLY:
            icon_only += 1
            if '<property name="toolbar-style">both-horiz</property>' not in old:
                raise SystemExit(f"{ident}: not a both-horiz toolbox")
            new = old.replace('name="toolbar-style">both-horiz<', 'name="toolbar-style">icons<', 1)
        elif klass == "GtkLabel":
            new = new.replace('name="style" value="italic"', 'name="style" value="normal"')
        elif klass == "GtkGrid":
            # Direct grid properties precede its first child. Never edit descendants.
            header, separator, rest = new.partition("<child")
            if '<property name="margin-start">3</property>' in header and '<property name="margin-end">3</property>' in header:
                header = header.replace('name="margin-start">3<', 'name="margin-start">4<')
                header = header.replace('name="margin-end">3<', 'name="margin-end">2<')
            header = header.replace('name="column-spacing">3<', 'name="column-spacing">4<')
            new = header + separator + rest
        # Parent grid spans contain captions. Apply just their changed lines using
        # separate non-overlapping replacements in the original document below.
        for before, after in zip(old.splitlines(True), new.splitlines(True)):
            if before != after:
                offset = old.index(before)
                edits.append((start + offset, start + offset + len(before), after))
    if icon_only != 2:
        raise SystemExit(f"expected 2 icon-only toolboxes on Home, found {icon_only}")
    for start, end, replacement in sorted(edits, reverse=True):
        text = text[:start] + replacement + text[end:]
    ET.fromstring(text)
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--tree", type=Path)
    source.add_argument("--installed", type=Path)
    parser.add_argument("--patch", type=Path)
    args = parser.parse_args()
    if args.tree and not args.patch:
        parser.error("--tree requires --patch (the source tree is read-only)")
    result = HEADER
    for part, module in APPS:
        rel = f"{part}/uiconfig/{module}/ui/notebookbar.ui"
        path = args.tree / rel if args.tree else args.installed / f"share/config/soffice.cfg/modules/{module}/ui/notebookbar.ui"
        before = path.read_text(encoding="utf-8")
        after = transform(before)
        if args.tree:
            result += "".join(difflib.unified_diff(before.splitlines(True), after.splitlines(True),
                                                 fromfile="a/" + rel, tofile="b/" + rel))
        elif after != before:
            path.write_text(after, encoding="utf-8")
    if args.patch:
        args.patch.write_text(result, encoding="utf-8")


if __name__ == "__main__":
    main()
