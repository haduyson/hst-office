"""Generate the ribbon collapse ladders (vcl/inc/HstRibbonLadders.hxx) as a follow-up patch.

Usage: scripts/patches/generate-ribbon-scale.py --tree DIR [--data data/ribbon/scaling-ladders.json]
           [--base patches/libreoffice/hst-ribbon-scale-ladders.patch]
           [--out patches/libreoffice/hst-ribbon-scale-ladders-collapse.patch] [--check]

The header first came in --base, which stays as committed; --out changes it to the current data, so
the series only ever gains patches.

DIR is a LibreOffice tree (or a copy of the three Tabbed notebookbar.ui files) with the ribbon content
patches applied. Every ladder is checked against it: the named merged group box must exist in the app's
notebookbar.ui with exactly the listed groups, in that order, and every step and fold entry must name
one of them. Any mismatch fails loudly, so content changes never silently disable a ladder. The output
is byte-stable; --check only compares it with the existing patch.
"""
import argparse
import difflib
import json
import os
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
UI = {"writer": "sw/uiconfig/swriter/ui/notebookbar.ui", "calc": "sc/uiconfig/scalc/ui/notebookbar.ui",
      "impress": "sd/uiconfig/simpress/ui/notebookbar.ui"}
STATES = {"M": 1, "S": 2, "C": 3}
HEADER = "vcl/inc/HstRibbonLadders.hxx"
FOLLOW_UP = """HST Office: collapse ladders of the ribbon tabs, with groups that collapse into their button (generated).

Generated by scripts/patches/generate-ribbon-scale.py from data/ribbon/scaling-ladders.json and checked
against the ribbon content of the three Tabbed notebookbar.ui files. Updates vcl/inc/HstRibbonLadders.hxx
of hst-ribbon-scale-ladders.patch to the current ladders: as in Office, the Home tab's groups shrink and
some collapse into one captioned button (state 3, hst-ribbon-group-button.patch) before any group folds
into the chevron popup.

"""

DESCRIPTION = """HST Office: collapse ladders of the ribbon tabs (generated).

Generated by scripts/patches/generate-ribbon-scale.py from data/ribbon/scaling-ladders.json and checked
against the ribbon content of the three Tabbed notebookbar.ui files, so it follows the content patches
in series. vcl/inc/HstRibbonLadders.hxx (new) lists, per merged group box, the order in which groups
shrink and the order in which they fold into the chevron popup; PriorityMergedHBox uses it when the
header exists (hst-ribbon-ladder-order.patch) and the default ladder otherwise.

"""


class LadderError(Exception):
    pass


def merged_boxes(path):
    """{box id: [group ids in visual order]} of the sfxlo-PriorityMergedHBox objects of a .ui file."""
    result = {}
    for box in ET.parse(path).iter("object"):
        if box.get("class") == "sfxlo-PriorityMergedHBox":
            result[box.get("id")] = [c.find("object").get("id") for c in box.findall("child")
                                     if c.find("object") is not None]
    return result


def validate(data, tree):
    cache = {}
    for ladder in data["ladders"]:
        app, box, groups = ladder["app"], ladder["box"], ladder["groups"]
        if app not in UI:
            raise LadderError(f"unknown app {app!r}")
        if app not in cache:
            path = os.path.join(tree, UI[app])
            if not os.path.isfile(path):
                raise LadderError(f"{app}: {UI[app]} not found under {tree}")
            cache[app] = merged_boxes(path)
        found = cache[app].get(box)
        if found is None:
            raise LadderError(f"{app}: no merged group box {box!r}")
        if found != groups:
            raise LadderError(f"{app}/{box}: groups are {found}, the ladder lists {groups}")
        for group, state in ladder["steps"]:
            if group not in groups or state not in STATES:
                raise LadderError(f"{app}/{box}: bad step {group!r} {state!r}")
        if sorted(ladder["fold"]) != sorted(groups):
            raise LadderError(f"{app}/{box}: the fold order must name every group exactly once")


def header(data):
    def ids(values):
        return ", ".join(f'u"{v}"' for v in values)
    lines = ["/* -*- Mode: C++; tab-width: 4; indent-tabs-mode: nil; c-basic-offset: 4 -*- */",
             "/*", " * This file is part of the LibreOffice project.", " *",
             " * This Source Code Form is subject to the terms of the Mozilla Public",
             " * License, v. 2.0. If a copy of the MPL was not distributed with this",
             " * file, You can obtain one at http://mozilla.org/MPL/2.0/.", " */", "",
             "#pragma once", "",
             "// HST Office: collapse ladders of the ribbon tabs. GENERATED by",
             "// scripts/patches/generate-ribbon-scale.py from data/ribbon/scaling-ladders.json; do not edit.", "",
             "#include <cstddef>", "#include <iterator>", "#include <string_view>", "", "namespace hst::ribbon::ladders", "{",
             "struct Step", "{", "    std::u16string_view group;", "    int state; // 1 medium, 2 small, 3 collapsed into its button", "};", "",
             "struct Ladder", "{", "    const std::u16string_view* groups; // visual order",
             "    std::size_t groupCount;", "    const Step* steps;", "    std::size_t stepCount;",
             "    const std::u16string_view* fold; // first folded first", "};", ""]
    entries = []
    for n, ladder in enumerate(data["ladders"]):
        name = f"{ladder['app']}_{ladder['box']}"
        lines.append(f"// {ladder['app']}: {ladder['box']}")
        lines.append(f"inline constexpr std::u16string_view {name}_groups[] = {{ {ids(ladder['groups'])} }};")
        steps = ", ".join(f'{{ u"{g}", {STATES[s]} }}' for g, s in ladder["steps"])
        lines.append(f"inline constexpr Step {name}_steps[] = {{ {steps} }};")
        lines.append(f"inline constexpr std::u16string_view {name}_fold[] = {{ {ids(ladder['fold'])} }};")
        lines.append("")
        entries.append(f"    {{ {name}_groups, std::size({name}_groups), {name}_steps, std::size({name}_steps), {name}_fold }},")
    lines += ["inline constexpr Ladder all[] = {", *entries, "};", "}", "",
              "/* vim:set shiftwidth=4 softtabstop=4 expandtab: */"]
    return "\n".join(lines) + "\n"


def patch_text(content):
    body = content.splitlines()
    out = [DESCRIPTION.rstrip("\n"), "", "--- /dev/null", f"+++ b/{HEADER}", f"@@ -0,0 +1,{len(body)} @@"]
    out += ["+" + line for line in body]
    return "\n".join(out) + "\n"


def base_header(path):
    """The header a base patch creates (its added lines)."""
    with open(path, encoding="utf-8") as handle:
        lines = handle.read().splitlines()
    start = lines.index(f"+++ b/{HEADER}") + 2  # after the hunk header
    return "".join(line[1:] + "\n" for line in lines[start:] if line.startswith("+"))


def follow_up_text(old, new):
    """A patch changing the header from old to new (3 lines of context, as diff -u)."""
    diff = difflib.unified_diff(old.splitlines(keepends=True), new.splitlines(keepends=True),
                                fromfile=f"a/{HEADER}", tofile=f"b/{HEADER}", n=3)
    body = list(diff)  # "--- a/x" and "+++ b/x" without dates, as the other patches
    if not body:
        raise LadderError("the data does not change the ladders of the base patch")
    return FOLLOW_UP + "".join(body)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tree", required=True)
    parser.add_argument("--data", default=os.path.join(ROOT, "data/ribbon/scaling-ladders.json"))
    parser.add_argument("--base", default=os.path.join(ROOT, "patches/libreoffice/hst-ribbon-scale-ladders.patch"))
    parser.add_argument("--out", default=os.path.join(ROOT, "patches/libreoffice/hst-ribbon-scale-ladders-collapse.patch"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with open(args.data, encoding="utf-8") as handle:
        data = json.load(handle)
    try:
        validate(data, args.tree)
        text = follow_up_text(base_header(args.base), header(data))
    except LadderError as error:
        print(f"ladder data does not match the ribbon content: {error}", file=sys.stderr)
        return 2
    if args.check:
        current = open(args.out, encoding="utf-8").read() if os.path.exists(args.out) else ""
        if current != text:
            print(f"{os.path.relpath(args.out, ROOT)} is out of date", file=sys.stderr)
            return 1
        print("up to date")
        return 0
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"wrote {os.path.relpath(args.out, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
