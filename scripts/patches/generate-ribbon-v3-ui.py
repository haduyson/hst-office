"""Generate patches/libreoffice/hst-ribbon-v3-ui.patch: the four ribbons' .ui files laid out as the v3 design.

usage: generate-ribbon-v3-ui.py --tree TREE [--out PATCH] [--check]
  TREE   a LibreOffice tree with the series applied up to the patch before hst-ribbon-v3-ui.patch
  --out  the patch to write (default: patches/libreoffice/hst-ribbon-v3-ui.patch)
  --check  only report what would change (exit 1 when a group of the data has no .ui counterpart)

The data is data/ribbon/ribbon-v3.json (every group's commands in order, with their kind); ribbon_v3_ui.py does the
per-group rewrite. Besides that rewrite:
- the groups of every tab stand in the data's order;
- a group of the data takes commands from another group of its tab (the HASON TECH group's "Giải pháp HASON TECH"
  joins "Phần mở rộng"); a group left empty is removed.
The command ids, menus, labels and images stay as they are: no command is added or lost (check-ribbon-v3-parity.py).
"""
import argparse
import difflib
import json
import os
import re
import sys

from lxml import etree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import ribbon_v3_ui as v3  # noqa: E402

HEADER = """HST Office: the ribbons of Writer, Sheets, Slides and Draw laid out as the owner-locked 1.0.3 (v3) design.

Generated by scripts/patches/generate-ribbon-v3-ui.py from data/ribbon/ribbon-v3.json; do not edit by hand.
- Every command of a group is one child of the group's grid, in the design's order (a toolbox of several buttons
  is split into one toolbox per button, the new toolboxes are named bxV3<button id>); the grid's property
  "hst-ribbon-layout" gives each child's kind (L large, M small with label, S icon only, W box, G gallery), the
  group's fixed 3-row layout and whether it keeps its sizes on a sparse tab. The ribbon's layout code places the
  children from it (hst-ribbon-v3-layout.patch).
- The groups of every tab stand in the design's order; the HASON TECH group's button joins the "Phần mở rộng"
  group, which has no HASON TECH caption any more.
- Labels inside a group that are not its caption (the "Thụt lề" and "Khoảng cách" captions of Writer's Layout >
  Paragraph boxes) are removed: the boxes keep their accessible names.
No command, menu, label or image changes; every command of the 1.0.2 ribbons stays.

License: these upstream files remain under their original license (MPL-2.0).
---
"""


def tab_of(grid):
    """The tab label id of the page holding grid (the notebook's tab child after the page)."""
    page = grid
    while page is not None and not (page.tag == "child" and page.getparent() is not None
                                    and page.getparent().get("class") == "sfxlo-NotebookbarTabControl"):
        page = page.getparent()
    if page is None:
        return None
    nxt = page.getnext()
    while nxt is not None and nxt.get("type") != "tab":
        nxt = nxt.getnext()
    return nxt.find("object").get("id") if nxt is not None else None


def depth(el):
    n = 0
    while el.getparent() is not None:
        el, n = el.getparent(), n + 1
    return n


def reorder_tab(box, group_ids):
    """Put the grid children of a tab's merged box in the data's order (other children keep their place after)."""
    kids = [c for c in box.findall("child") if c.find("object") is not None]
    by_id = {c.find("object").get("id"): c for c in kids}
    ordered = [by_id[g] for g in group_ids if g in by_id]
    if [c for c in kids if c in ordered] == ordered:
        return False
    first = min(box.index(c) for c in ordered)
    for c in ordered:
        box.remove(c)
    for i, c in enumerate(ordered):
        box.insert(first + i, c)
    for i, c in enumerate(kids):
        pack = c.find("packing")
        pos = pack.find("property[@name='position']") if pack is not None else None
        if pos is not None:
            pos.text = str(box.index(c) - min(box.index(k) for k in kids))
    return True


def borrow_units(root, grid, group, tab_grids):
    """Move into grid the units of group's items that stand in another grid of the same tab."""
    _, _, own = v3.group_parts(grid)
    keys = {u.key for u in own}
    for item in group["items"]:
        if item["k"] in keys:
            continue
        for other in tab_grids:
            if other is grid:
                continue
            _, _, units = v3.group_parts(other)
            unit = next((u for u in units if u.key == item["k"]), None)
            if unit is None:
                continue
            other.remove(unit.child)
            grid.append(unit.child)
            _, _, rest = v3.group_parts(other)
            if not rest:  # an emptied group goes
                holder = other.getparent()
                prev = holder.getprevious()
                if prev is not None and prev.tag is ET.Comment:
                    holder.getparent().remove(prev)
                holder.getparent().remove(holder)
            break


def drop_inner_labels(grid):
    """Labels in a group's content (not its caption on the lowest row) are removed."""
    labels = []
    for child in grid.findall("child"):
        obj = child.find("object")
        if obj is not None and obj.get("class") == "GtkLabel":
            pack = child.find("packing")
            top = pack.find("property[@name='top-attach']") if pack is not None else None
            labels.append((int(top.text) if top is not None else 0, child))
    boxes = [c for c in grid.findall("child") if c.find("object") is not None and v3.is_caption(c.find("object"))
             and c.find("object").get("class") == "GtkBox"]
    if boxes:  # the caption is the box of the label and the launcher
        for _, child in labels:
            grid.remove(child)
    elif len(labels) > 1:
        bottom = max(t for t, _ in labels)
        for t, child in labels:
            if t != bottom:
                grid.remove(child)


def expand_box(box):
    """The tab's merged box takes the page's width: the v3 fit folds its groups down to the chevron, so a box packed
    at its size request (the Help tab) got the chevron's width only and folded every group."""
    pack = box.getparent().find("packing")
    if pack is None:
        return
    prop = pack.find("property[@name='expand']")
    if prop is None:
        prop = ET.SubElement(pack, "property", name="expand")
        pack.insert(0, prop)
    prop.text = "True"


def rewrite_app(path, app):
    tree = ET.parse(path)
    root = tree.getroot()
    used = {o.get("id") for o in root.iter("object") if o.get("id")}
    grids = {}
    for obj in root.iter("object"):
        if obj.get("class") == "GtkGrid":
            grids.setdefault(obj.get("id"), []).append(obj)
    count = 0
    for tab in app["tabs"]:
        tab_grids = [g for gl in grids.values() for g in gl if tab_of(g) == tab["id"]]
        box = None
        for group in tab["groups"]:
            found = [g for g in grids.get(group["id"], []) if tab_of(g) == tab["id"]]
            if len(found) != 1:
                raise KeyError(f"{app['id']} {tab['id']} {group['id']}: {len(found)} grids")
            grid = found[0]
            borrow_units(root, grid, group, tab_grids)
            drop_inner_labels(grid)
            count += v3.rewrite_group(grid, group, used)
            ET.indent(grid, space="  ", level=depth(grid))
            box = grid.getparent().getparent()
        if box is not None:
            reorder_tab(box, [g["id"] for g in tab["groups"]])
            expand_box(box)
    text = ET.tostring(tree, encoding="UTF-8", xml_declaration=True).decode("utf-8")
    return text.replace("--><interface", "-->\n<interface", 1) + "\n", count


def keep_authored_spelling(before, after):
    """after's lines, with the authored text kept where lxml only respelled a line (" />" as "/>")."""
    old, new = before.splitlines(True), after.splitlines(True)
    norm = lambda line: re.sub(r"\s+/>", "/>", line)  # noqa: E731
    out = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, old, new, autojunk=False).get_opcodes():
        if tag == "replace" and i2 - i1 == j2 - j1 and all(norm(a) == norm(b) for a, b in zip(old[i1:i2], new[j1:j2])):
            out.extend(old[i1:i2])
        else:
            out.extend(new[j1:j2])
    return "".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tree", required=True)
    ap.add_argument("--out", default=os.path.join(ROOT, "patches", "libreoffice", "hst-ribbon-v3-ui.patch"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    with open(os.path.join(ROOT, "data", "ribbon", "ribbon-v3.json"), encoding="utf-8") as handle:
        data = json.load(handle)
    out, total = [HEADER], 0
    for app in data["apps"]:
        rel = v3.UI_FILES[app["id"]]
        path = os.path.join(args.tree, rel)
        with open(path, encoding="utf-8") as handle:
            before = handle.read()
        after, count = rewrite_app(path, app)
        total += count
        if not before.startswith("<?xml version='1.0'") and after.startswith("<?xml version='1.0'"):
            after = after.replace("<?xml version='1.0' encoding='UTF-8'?>", before.splitlines()[0], 1)
        after = keep_authored_spelling(before, after)
        out.extend(difflib.unified_diff(before.splitlines(True), after.splitlines(True), "a/" + rel, "b/" + rel))
        print(f"{app['id']}: {count} commands placed")
    if not args.check:
        with open(args.out, "w", encoding="utf-8") as handle:
            handle.write("".join(out))
        print(f"wrote {args.out} ({total} commands)")


if __name__ == "__main__":
    main()
