"""Generate patches/libreoffice/hst-ribbon-tooltip-descriptions.patch from data/ribbon/tooltip-descriptions.json.

  python3 scripts/patches/generate-ribbon-tooltips.py [--po PRISTINE_SFX2_VI_PO] [--check]

The patch adds sfx2/source/notebookbar/HstRibbonTooltipTable.hrc (the command -> sentence table read by
HstRibbonTooltip.cxx of hst-ribbon-rich-tooltips.patch; English msgid) and appends the Vietnamese entries at the end
of translations/source/vi/sfx2/messages.po. The .po hunk is made against the pristine tarball file and goes in before the
upstream entry ANCHOR, with three lines of upstream context on each side. --po defaults to extracting that file from upstream/cache. --check exits
1 when the committed patch differs from what the data gives.
"""
import argparse
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = os.path.join(ROOT, "data", "ribbon", "tooltip-descriptions.json")
PATCH = os.path.join(ROOT, "patches", "libreoffice", "hst-ribbon-tooltip-descriptions.patch")
TARBALL = os.path.join(os.environ.get("HST_UPSTREAM_CACHE_ROOT", ROOT), "upstream", "cache", "libreoffice", "libreoffice-translations-26.8.3.1.tar.xz")
PO = "translations/source/vi/sfx2/messages.po"
HRC = "sfx2/source/notebookbar/HstRibbonTooltipTable.hrc"
# the entries go in before this upstream entry, in the middle of the file: no other patch edits it or its neighbours,
# and patches that append at the end of the file (hst-backstage-print.patch) cannot move the hunk's context
ANCHOR = 'msgctxt "addtargetdialog|checkboxCaseSensitive"'
APP_BITS = {"writer": "TIP_WRITER", "calc": "TIP_CALC", "impress": "TIP_IMPRESS", "draw": "TIP_DRAW"}
HEADER = """\
HST Office: the sentences of the rich ribbon tooltips (generated by scripts/patches/generate-ribbon-tooltips.py
from data/ribbon/tooltip-descriptions.json; do not edit). HstRibbonTooltipTable.hrc maps a ribbon command to the
sentence shown under its bold name and shortcut (hst-ribbon-rich-tooltips.patch); the Vietnamese text is added to the
sfx2 catalogue.

License: these upstream files remain under their original license (MPL-2.0).
---
"""


def entries(data):
    """[(command, app or None, en, vi)] in a stable order: the common sentences, then each app's own."""
    rows = [(cmd, None, t["en"], t["vi"]) for cmd, t in sorted(data["descriptions"].items())]
    for app, table in sorted(data.get("app_descriptions", {}).items()):
        rows += [(cmd, app, t["en"], t["vi"]) for cmd, t in sorted(table.items())]
    return rows


def titles(data):
    """[(command, app, en, vi)] of the short tooltip titles ("app_titles"): they replace the command's label as the
    bold first line; the shortcut is still added in brackets."""
    return [(cmd, app, t["en"], t["vi"]) for app, table in sorted(data.get("app_titles", {}).items())
            for cmd, t in sorted(table.items())]


def context(cmd, app, kind="Tip"):
    return f"HstRibbon{kind}|{app}|{cmd}" if app else f"HstRibbon{kind}|{cmd}"


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def hrc_lines(rows, title_rows=()):
    lines = ["/* -*- Mode: C++; tab-width: 4; indent-tabs-mode: nil; c-basic-offset: 4 -*- */",
             "// Generated by scripts/patches/generate-ribbon-tooltips.py from data/ribbon/tooltip-descriptions.json.",
             "// The sentence of a ribbon command, shown under its bold name and shortcut (HstRibbonTooltip.cxx).",
             "#pragma once", "", "#include <sal/types.h>", "#include <unotools/resmgr.hxx>", "",
             "#include <string_view>", "", "#ifndef NC_", "#define NC_(Context, String) TranslateId(Context, u8##String)",
             "#endif", "", "// HstRibbonTip::nApps: the apps an entry is for; 0 = every app (an app's own entry wins)",
             "constexpr sal_uInt8 TIP_WRITER = 1;", "constexpr sal_uInt8 TIP_CALC = 2;",
             "constexpr sal_uInt8 TIP_IMPRESS = 4;", "constexpr sal_uInt8 TIP_DRAW = 8;", "",
             "struct HstRibbonTip", "{", "    std::u16string_view pCommand;", "    sal_uInt8 nApps;",
             "    TranslateId aText;", "};", "", "constexpr HstRibbonTip aHstRibbonTips[] = {"]
    for cmd, app, en, _vi in rows:
        bits = APP_BITS[app] if app else "0"
        lines.append(f"    {{ u{c_string(cmd)}, {bits}, NC_({c_string(context(cmd, app))}, {c_string(en)}) }},")
    lines += ["};", "", "// the short name shown in bold instead of the command's label (an app's own design)",
              "constexpr HstRibbonTip aHstRibbonTitles[] = {"]
    for cmd, app, en, _vi in title_rows:
        lines.append(f"    {{ u{c_string(cmd)}, {APP_BITS[app]}, NC_({c_string(context(cmd, app, 'Title'))}, {c_string(en)}) }},")
    if not title_rows:
        lines.append("    { u\"\", 0, TranslateId() },")
    lines += ["};", "", "/* vim:set shiftwidth=4 softtabstop=4 expandtab: */"]
    return lines


def po_quote(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def po_lines(rows, title_rows=()):
    lines = []
    for kind, table in (("Tip", rows), ("Title", title_rows)):
        for cmd, app, en, vi in table:
            lines += [f"#. hst{kind}", f"#: {HRC}", f"msgctxt {po_quote(context(cmd, app, kind))}",
                      f"msgid {po_quote(en)}", f"msgstr {po_quote(vi)}", ""]
    return lines


def pristine_po(path):
    if path:
        with open(path, encoding="utf-8") as handle:
            return handle.read().split("\n")
    member = f"libreoffice-26.8.3.1/{PO}"
    text = subprocess.run(["tar", "-xJOf", TARBALL, member], check=True, capture_output=True).stdout.decode("utf-8")
    return text.split("\n")


def build(data, po):
    rows, title_rows = entries(data), titles(data)
    hrc = hrc_lines(rows, title_rows)
    out = [f"--- /dev/null", f"+++ b/{HRC}", f"@@ -0,0 +1,{len(hrc)} @@"] + ["+" + line for line in hrc]
    at = po.index(ANCHOR) - 2  # the anchor entry starts with its "#." and "#:" lines
    before, after, added = po[at - 3:at], po[at:at + 3], po_lines(rows, title_rows)
    start = at - 3 + 1
    out += [f"--- a/{PO}", f"+++ b/{PO}", f"@@ -{start},6 +{start},{6 + len(added)} @@"]
    out += [" " + line for line in before] + ["+" + line for line in added] + [" " + line for line in after]
    return HEADER + "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--po", help="pristine translations/source/vi/sfx2/messages.po (default: from the tarball)")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with open(DATA, encoding="utf-8") as handle:
        data = json.load(handle)
    text = build(data, pristine_po(args.po))
    if args.check:
        with open(PATCH, encoding="utf-8") as handle:
            same = handle.read() == text
        print("patch up to date" if same else "patch differs from the data: regenerate it")
        return 0 if same else 1
    with open(PATCH, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"wrote {PATCH} ({len(entries(data))} sentences)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
