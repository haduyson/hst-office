"""Generate the TCVN3/VNI decoding header used by the WMF import patch (equation previews).

Usage: python3 scripts/patches/generate-legacy-vn-font-table.py            # print the header
       python3 scripts/patches/generate-legacy-vn-font-table.py --check    # header in the patch is current

The tables come from data/vietnamese/encoding-maps.json, the same data the HST Vietnamese
tools convert document text with (docs/ENCODING_SOURCES.md). The header is carried as a new
file by patches/libreoffice/hst-emfio-legacy-vn-fonts.patch.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = os.path.join(ROOT, "data", "vietnamese", "encoding-maps.json")
PATCH = os.path.join(ROOT, "patches", "libreoffice", "hst-emfio-legacy-vn-fonts.patch")
HEADER_PATH = "emfio/source/reader/hstlegacyvn.hxx"


def _rows(values, per_row=8):
    return "\n".join("    " + ", ".join(values[i:i + per_row]) + "," for i in range(0, len(values), per_row))


def generate(data=None):
    enc = (data or json.load(open(DATA, encoding="utf-8")))["encodings"]
    tcvn3, vni = enc["tcvn3"], enc["vni"]
    lower = [0] * 128
    for key, letter in tcvn3["map"].items():
        lower[int(key, 16) - 0x80] = ord(letter)
    upper = [ord(chr(c).upper()) if c else 0 for c in lower]
    cp1252 = []
    for b in range(0x80, 0xA0):
        try:
            cp1252.append(ord(bytes([b]).decode("cp1252")))
        except UnicodeDecodeError:
            cp1252.append(b)  # undefined in Windows-1252: keep the code (as Windows does)
    pairs = sorted((bytes.fromhex(k), v) for k, v in vni["map"].items())
    vni_rows = [f"{{ 0x{k[0]:02X}, 0x{(k[1] if len(k) > 1 else 0):02X}, 0x{ord(v):04X} }}" for k, v in pairs]
    fallback = {k: v for k, v in tcvn3["fontFallback"].items() if k != "default"}
    special = "\n".join(
        f'    if (o3tl::matchIgnoreAsciiCase(rFamily, u"{name}"))\n        return u"{font}"_ustr;'
        for name, font in sorted(fallback.items()) if font != tcvn3["fontFallback"]["default"])
    hexes = lambda xs: [f"0x{x:04X}" for x in xs]  # noqa: E731
    return f"""/* -*- Mode: C++; tab-width: 4; indent-tabs-mode: nil; c-basic-offset: 4 -*- */
/*
 * This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at http://mozilla.org/MPL/2.0/.
 */
// HST Office: legacy Vietnamese 8-bit fonts in WMF text (TCVN3 ".VnTime", VNI "VNI-Times").
// Generated by scripts/patches/generate-legacy-vn-font-table.py from data/vietnamese/encoding-maps.json.

#pragma once

#include <o3tl/string_view.hxx>
#include <rtl/character.hxx>
#include <rtl/ustrbuf.hxx>
#include <rtl/ustring.hxx>

#include <string_view>
#include <vector>

namespace emfio::legacyvn
{{
enum class Encoding
{{
    None,
    Tcvn3, // ".VnTime", ".VnArial" ...
    Tcvn3Upper, // ".VnTimeH", ".VnArialH" ...: uppercase glyphs at the lowercase codes
    Vni // "VNI-Times", "VNI-Helve" ...: letter + tone-mark byte
}};

// TCVN3 bytes 0x80-0xFF (0 = not a TCVN3 letter, decoded as Windows-1252)
constexpr sal_Unicode aTcvn3[128] = {{
{_rows(hexes(lower))}
}};
constexpr sal_Unicode aTcvn3Upper[128] = {{
{_rows(hexes(upper))}
}};
// Windows-1252 bytes 0x80-0x9F (0xA0-0xFF are Latin-1)
constexpr sal_Unicode aCp1252High[32] = {{
{_rows(hexes(cp1252))}
}};

struct VniEntry
{{
    unsigned char nFirst;
    unsigned char nSecond; // 0: single byte
    sal_Unicode cLetter;
}};
constexpr VniEntry aVni[] = {{
{_rows(vni_rows, 4)}
}};

inline Encoding GetEncoding(std::u16string_view rFamily)
{{
    if (rFamily.size() > 3 && o3tl::matchIgnoreAsciiCase(rFamily, u"{tcvn3["fontPrefix"]}"))
        return rFamily.back() == '{tcvn3["upperFontSuffix"]}' ? Encoding::Tcvn3Upper : Encoding::Tcvn3;
    if (rFamily.size() > 4 && o3tl::matchIgnoreAsciiCase(rFamily, u"{vni["fontPrefix"]}"))
        return Encoding::Vni;
    return Encoding::None;
}}

// Unicode font that replaces the legacy font
inline OUString GetReplacementFamily(std::u16string_view rFamily)
{{
{special}
    return u"{tcvn3["fontFallback"]["default"]}"_ustr;
}}

inline sal_Unicode DecodeCp1252(unsigned char c)
{{
    return (c >= 0x80 && c < 0xA0) ? aCp1252High[c - 0x80] : c;
}}

// Decode nLen legacy bytes; rBytes receives the number of bytes behind each decoded character.
inline OUString Decode(Encoding eEncoding, const char* pChars, sal_Int32 nLen, std::vector<sal_Int32>& rBytes)
{{
    OUStringBuffer aBuf(nLen);
    rBytes.clear();
    for (sal_Int32 i = 0; i < nLen;)
    {{
        const unsigned char c = static_cast<unsigned char>(pChars[i]);
        sal_Unicode cOut = 0;
        sal_Int32 nUsed = 1;
        if (eEncoding == Encoding::Vni)
        {{
            const unsigned char cNext = i + 1 < nLen ? static_cast<unsigned char>(pChars[i + 1]) : 0;
            for (const VniEntry& rEntry : aVni)
            {{
                if (rEntry.nFirst == c && (rEntry.nSecond == 0 || rEntry.nSecond == cNext))
                {{
                    cOut = rEntry.cLetter;
                    nUsed = rEntry.nSecond ? 2 : 1;
                    if (nUsed == 2)
                        break; // a letter + mark pair wins over the single letter
                }}
            }}
        }}
        else if (c >= 0x80)
            cOut = (eEncoding == Encoding::Tcvn3Upper ? aTcvn3Upper : aTcvn3)[c - 0x80];
        if (!cOut)
        {{
            cOut = DecodeCp1252(c);
            if (eEncoding == Encoding::Tcvn3Upper)
                cOut = static_cast<sal_Unicode>(rtl::toAsciiUpperCase(cOut));
        }}
        aBuf.append(cOut);
        rBytes.push_back(nUsed);
        i += nUsed;
    }}
    return aBuf.makeStringAndClear();
}}
}}

/* vim:set shiftwidth=4 softtabstop=4 expandtab: */
"""


def header_in_patch(path=PATCH):
    """Text of the new header file carried by the patch (lines after its '+++ b/...' hunk)."""
    lines, inside = [], False
    for line in open(path, encoding="utf-8").read().splitlines():
        if line.startswith("+++ b/"):
            inside = line[6:].split()[0] == HEADER_PATH
            continue
        if inside:
            if line.startswith("diff ") or line.startswith("--- "):
                break
            if line.startswith("+"):
                lines.append(line[1:])
    return "\n".join(lines) + "\n"


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        if header_in_patch() != text:
            print(f"{os.path.relpath(PATCH, ROOT)}: {HEADER_PATH} differs from the generator output")
            return 1
        print("legacy Vietnamese font table: patch is current")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
