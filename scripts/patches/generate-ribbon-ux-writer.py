def ribbon_commands(root, menus=True):
    """Commands of the ribbon's buttons (and, with menus, of its menus)."""
    found = {lib.prop(o, "action-name") for o in root.iter("object") if menus or o.get("class") != "GtkMenuItem"}
    return found - {None}


def build_ui(root):
    engine = Engine(root)
    engine.menus = MENUS
    before = ribbon_commands(root, menus=False)
    before_menus = used_menus(root)
    for button_id, box_id in INTO:
        hold = engine.take(("btn", button_id, "I")).find("object/child")
        lib.find(root, box_id).append(hold)
    for button_id in DROP_BUTTONS:
        box_hold, box = lib.holder(root, lib.find(root, button_id))
        engine.detach(lib.find(root, button_id))
        if box.find("child") is None:
            engine.detach(box)
    taken = {gid: [[engine.take(item) for item in column] for column in spec.get("columns", [])]
             for gid, spec in GROUPS.items()}
    cells = {gid: [(engine.take(item), left, top, width) for item, left, top, width in spec["cells"]]
             for gid, spec in GROUPS.items() if "cells" in spec}
    for block in BLOCKS:
        engine.detach(lib.find(root, block))
    for gid, spec in GROUPS.items():
        if "new" in spec:
            continue
        engine.lay_out(lib.find(root, gid), taken[gid] or None, cells.get(gid))
    for box_id, order in TABS.items():
        box = lib.find(root, box_id)
        holders = {h.find("object").get("id"): h for h in box.findall("child")}
        for hold in holders.values():
            box.remove(hold)
        for position, gid in enumerate(order):
            if gid in holders:
                hold = holders[gid]
            else:
                hold = lib.fragment("<child/>")[0]
                grid = engine.new_grid(gid, GROUPS[gid]["new"])
                hold.append(grid)
                engine.lay_out(grid, taken[gid])
            for key, value in (("expand", "False"), ("fill", "True"), ("position", position)):
                lib.packing(hold, key, value)
            lib.insert_child(box, hold)
    for gid, pair in CAPTIONS.items():
        caption = engine.caption(lib.find(root, gid)).find("object")
        label = caption if caption.get("class") == "GtkLabel" else next(
            o for o in caption.iter("object") if o.get("class") == "GtkLabel")
        engine.set_text(label, "label", "group", pair)
    for label_id, pair in TAB_LABELS.items():
        engine.set_text(lib.find(root, label_id), "label", "tab", pair)
    for button_id, pair in LABELS.items():
        engine.set_text(lib.find(root, button_id), "hst-ribbon-label", "label", pair)
    for button_id, icon in ICONS.items():
        lib.set_prop(lib.find(root, button_id), "icon-name", icon)
    for button in root.iter("object"):
        command = lib.prop(button, "action-name")
        if button.get("class") in lib.BUTTON_CLASSES and command in DESCRIPTIONS:
            engine.set_text(button, "hst-ribbon-description", "tip", DESCRIPTIONS[command])
    for label in [o for o in root.iter("object") if (o.get("id") or "").startswith("txt")]:
        for relation in label.findall("accessibility/relation"):  # gla11y: label-for needs labelled-by back
            target = lib.find(root, relation.get("target"))
            access = target.find("accessibility")
            if access is None:
                access = ET.SubElement(target, "accessibility")
            ET.SubElement(access, "relation", {"type": "labelled-by", "target": label.get("id")})
    drop_unused_menus(root, before_menus)
    lib.check_unique(root)
    left = before - ribbon_commands(root) - {c for split in commands.SPLIT_BUTTONS for c, _label in split[4]}
    left -= IN_PASTE_DROPDOWN
    if left != LEFT_RIBBON:
        raise lib.RibbonUxError(f"commands that left the ribbon {sorted(left)} differ from LEFT_RIBBON")
    return engine


def used_menus(root):
    return {o.get("id").partition(":")[2] for o in root.iter("object") if ":" in (o.get("id") or "")}


def drop_unused_menus(root, before):
    """Top-level menus only the removed blocks opened."""
    for menu in [m for m in root.findall("object") if m.get("class") == "GtkMenu"]:
        if menu.get("id") in before and menu.get("id") not in used_menus(root):
            root.remove(menu)


def po_text(tree, strings):
    unique = {}
    for context, msgid, msgstr in strings:
        if unique.setdefault((context, msgid), msgstr) != msgstr:
            raise lib.RibbonUxError(f"{context} {msgid!r}: two translations")
    return lib.po_with_entries(lib.read(tree, PO), UI, [(c, m, s) for (c, m), s in sorted(unique.items())], PO_ANCHOR)


def patch_texts(tree, tarballs):
    old = lib.read(tree, UI)
    root = lib.parse_text(old)
    engine = build_ui(root)
    ui = lib.serialize_like(old, root)
    strings = engine.strings + [cxx.ND30_PO]
    diffs = [lib.file_diff(UI, old, ui), lib.file_diff(PO, lib.read(tree, PO), po_text(tree, strings)),
             lib.file_diff(SUPPR, lib.read(tree, SUPPR), lib.suppr(tree, SUPPR, UI, lib.parse_text(ui)))]
    return [(OUT, DESCRIPTION, diffs),
            (OUT_COMMANDS, DESCRIPTION_COMMANDS, commands.diffs(tree) + cxx.diffs(tree, tarballs))]


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tree", required=True)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--tarballs", default=os.environ.get("HST_LO_TARBALLS", TARBALLS),
                        help="pinned LibreOffice tarballs, for files the series does not touch")
    args = parser.parse_args()
    try:
        outputs = patch_texts(args.tree, args.tarballs)
    except (lib.RibbonUxError, OSError, ValueError, StopIteration, subprocess.CalledProcessError) as error:
        print(f"cannot generate the Writer ribbon: {error}", file=sys.stderr)
        return 2
    return max(lib.write_patch(out, description, diffs, check=args.check) for out, description, diffs in outputs)


if __name__ == "__main__":
    sys.exit(main())
