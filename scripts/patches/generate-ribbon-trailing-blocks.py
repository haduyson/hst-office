"""Generate the .ui part of the patch that trims the ribbon tabs' trailing blocks and puts the contextual tabs last.

Usage: scripts/patches/generate-ribbon-trailing-blocks.py --tree DIR [--out FILE] [--check]

DIR is a LibreOffice tree with the series applied up to (not including) the generated patch. For the Tabbed
notebookbar.ui of Writer, Sheets and Slides (Draw has its own ribbon work):
  - a tab's trailing block (the tab menu "Tab ▾" and the small icons beside it, sfxlo-DropdownBox) whose menu and
    icons hold no command that is not elsewhere on the ribbon is removed (scripts/ribbon/tab-menu-commands.py);
    this also removes Slides' 3D block, whose menu "Menu 3d" exists only in Draw's file;
  - the other blocks lose the icons that repeat a command shown elsewhere on the ribbon (a toolbox left empty
    goes too). The File and Home blocks (Home's is the Tools group) and the Extension tab's block (hidden in code
    while no extension adds buttons) are left as they are;
  - the Help and Extension tabs move before the contextual tabs, so a contextual tab (Table, Picture...) opens at
    the end of the row instead of pushing Help and Extension to the right.
The edits are made on the text; the output is byte-stable; --check only compares with the existing file.
"""
import argparse
import difflib
import importlib.util
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
_spec = importlib.util.spec_from_file_location("tab_menu_commands", os.path.join(ROOT, "scripts/ribbon/tab-menu-commands.py"))
menus = importlib.util.module_from_spec(_spec)
sys.path.insert(0, os.path.join(ROOT, "scripts/ribbon"))
_spec.loader.exec_module(menus)

UI = {app: path for app, path in menus.UI.items()}
KEEP = ("File-Menu", "Home-Menu", "Extension-Menu")
LAST_TABS = ("HelpLabel", "ExtensionLabel")
OUT = os.path.join(ROOT, "patches", "libreoffice", "hst-ribbon-trailing-blocks.patch")
DESCRIPTION = """HST Office: fewer trailing blocks on the ribbon tabs; contextual tabs open last (generated).

Generated by scripts/patches/generate-ribbon-trailing-blocks.py from the Tabbed notebookbar.ui of Writer,
Sheets and Slides. A tab's trailing block (a button named like the tab, opening a tab menu, and small icons)
had no caption and mostly repeated commands of the tab:
- blocks whose menu and icons hold no command that is not elsewhere on the ribbon go (scripts/ribbon/
  tab-menu-commands.py lists them): Print Preview and Form in Writer and Sheets; Form, Master Slide and 3D in
  Slides, whose 3D button opened "Menu 3d", a menu only Draw's file has;
- the other blocks lose their icons that repeat a ribbon command; File, Home (the Tools group) and the
  Extension tab's block (hidden while no extension adds buttons, hst-ribbon-addons-block.patch) stay;
- Help and Extension come before the contextual tabs, so a contextual tab opens at the end of the tab row
  instead of pushing Help and Extension to the right.
The menus stay in the files; every command is still in the menu bar and the feature search (Alt+Q).

License: these upstream files remain under their original license (MPL-2.0).
---
"""


class TrimError(Exception):
    pass


def enclosing_child(lines, index):
    """(start, end) line indexes, end inclusive, of the <child> element around the object opened at `index`."""
    indent = len(lines[index]) - len(lines[index].lstrip())
    start = index - 1
    while not (lines[start].strip().startswith("<child") and len(lines[start]) - len(lines[start].lstrip()) == indent - 2):
        start -= 1
    return start, element_end(lines, start)


def element_end(lines, start):
    indent = len(lines[start]) - len(lines[start].lstrip())
    end = start + 1
    while not (lines[end].strip() == "</child>" and len(lines[end]) - len(lines[end].lstrip()) == indent):
        end += 1
    return end


def object_line(lines, klass, ident):
    pattern = f'<object class="{klass}" id="{ident}">'
    found = [i for i, line in enumerate(lines) if pattern in line]
    if len(found) != 1:
        raise TrimError(f"{klass} {ident}: {len(found)} matches")
    return found[0]


def trim(text, blocks):
    lines = text.splitlines(keepends=True)
    cut = []  # (start, end) ranges to drop
    for ident, block in blocks.items():
        if ident in KEEP or block["hidden"]:
            continue
        start = object_line(lines, "sfxlo-DropdownBox", ident)
        block_range = enclosing_child(lines, start)
        if not block["only_here"]:
            cut.append(block_range)
            continue
        duplicates = set(block["duplicate_icons"]) - set(block["only_here"])
        for i in range(block_range[0], block_range[1]):
            match = re.search(r'<property name="action-name">\.uno:([^<]+)</property>', lines[i])
            if not match or match.group(1) not in duplicates:
                continue
            j = i
            while '<object class="Gtk' not in lines[j] or "ToolButton" not in lines[j]:
                j -= 1
            cut.append(enclosing_child(lines, j))
        # a toolbox left without items goes too
        for i in range(block_range[0], block_range[1]):
            if '<object class="sfxlo-NotebookbarToolBox"' in lines[i]:
                box = enclosing_child(lines, i)
                items = [k for k in range(box[0], box[1]) if "ToolButton" in lines[k] and "<object" in lines[k]]
                if items and all(any(s <= k <= e for s, e in cut) for k in items):
                    cut.append(box)
    keep = [True] * len(lines)
    for start, end in cut:
        for k in range(start, end + 1):
            keep[k] = False
    return "".join(line for line, k in zip(lines, keep) if k)


def page_pair(lines, tab_id):
    """(start, end) of the page <child> and the following tab <child> whose label is tab_id."""
    label = object_line(lines, "GtkLabel", tab_id)
    tab_start, tab_end = enclosing_child(lines, label)
    page_end = tab_start - 1
    indent = len(lines[page_end]) - len(lines[page_end].lstrip())
    page_start = page_end - 1
    while not (lines[page_start].strip() == "<child>" and len(lines[page_start]) - len(lines[page_start].lstrip()) == indent):
        page_start -= 1
    return page_start, tab_end


def move_last_tabs(text, first_contextual):
    lines = text.splitlines(keepends=True)
    pairs = [page_pair(lines, tab) for tab in LAST_TABS]
    target = page_pair(lines, first_contextual)[0]
    moved = [line for start, end in pairs for line in lines[start:end + 1]]
    drop = {k for start, end in pairs for k in range(start, end + 1)}
    out = []
    for k, line in enumerate(lines):
        if k == target:
            out.extend(moved)
        if k not in drop:
            out.append(line)
    return "".join(out)


def first_contextual_tab(path):
    from office_parity_ui import parse_notebookbar
    pages = parse_notebookbar(path)
    for page in pages:
        if page["contexts"] and "default" not in page["contexts"]:
            return page["id"]
    raise TrimError(f"{path}: no contextual tab")


def transform(path):
    with open(path, encoding="utf-8") as handle:
        old = handle.read()
    new = trim(old, menus.analyse(path))
    new = move_last_tabs(new, first_contextual_tab(path))
    return old, new


def diff_text(tree):
    parts = [DESCRIPTION]
    for path in UI.values():
        old, new = transform(os.path.join(tree, path))
        parts.extend(difflib.unified_diff(old.splitlines(keepends=True), new.splitlines(keepends=True),
                                          f"a/{path}", f"b/{path}", n=3))
    return "".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tree", required=True)
    parser.add_argument("--out", default=OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = diff_text(args.tree)
    if args.check:
        with open(args.out, encoding="utf-8") as handle:
            ok = handle.read() == text
        print(("ok: " if ok else "stale: ") + args.out, file=sys.stdout if ok else sys.stderr)
        return 0 if ok else 1
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
