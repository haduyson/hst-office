"""Generate patches/libreoffice/hst-ribbon-mail-merge.patch: the Writer "Gửi thư" tab in the order of the familiar
step-by-step mail merge, driven by the HST Trộn thư commands (org.hst.office.mailmerge:, mail_merge_handler.py).

Usage: scripts/patches/generate-mail-merge-ribbon.py --tree DIR [--out PATCH] [--check]

DIR is a LibreOffice tree with the series applied up to (not including) this patch (a fresh apply). The "Tạo" group
stays; the groups Bắt đầu trộn thư, Soạn và chèn trường, Xem trước kết quả and Hoàn tất are rewritten (same group
and caption ids, so other ribbon patches can build on them) and the Vietnamese strings go to sw/messages.po.
Removed from the tab (still in the menus): Nguồn sổ địa chỉ, Nguồn dữ liệu, Trường, the engine's record buttons
(they need the wizard first), Trộn thư (MergeDialog) and Email (send the document)."""
import argparse
import difflib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mail_merge_ribbon_xml import button, cell, group, hbox, toolbox  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
UI = "sw/uiconfig/swriter/ui/notebookbar.ui"
PO = "translations/source/vi/sw/messages.po"
OUT = os.path.join(ROOT, "patches", "libreoffice", "hst-ribbon-mail-merge.patch")
# context id -> (English source, Vietnamese)
STRINGS = {
    "btnHstMMRecipients": ("Select Recipients", "Chọn người nhận"),
    "btnHstMMRecipientsTip": ("Select the recipient list: a spreadsheet (.xlsx, .ods) or .csv file",
                              "Chọn danh sách người nhận: tệp bảng tính (.xlsx, .ods) hoặc .csv"),
    "btnHstMMEditRecipients": ("Edit Recipient List", "Sửa danh sách người nhận"),
    "btnHstMMWizard": ("Mail Merge Wizard (Full)", "Trình hướng dẫn trộn thư (đầy đủ)"),
    "btnHstMMInsertField": ("Insert Merge Field", "Chèn trường trộn"),
    "btnHstMMFieldFormat": ("Field Format", "Định dạng trường"),
    "btnHstMMPreview": ("Preview Results", "Xem trước kết quả"),
    "btnHstMMFirst": ("First Record", "Bản ghi đầu"),
    "btnHstMMPrev": ("Previous Record", "Bản ghi trước"),
    "btnHstMMRecord": ("Record", "Bản ghi"),
    "btnHstMMNext": ("Next Record", "Bản ghi sau"),
    "btnHstMMLast": ("Last Record", "Bản ghi cuối"),
    "btnHstMMFind": ("Find Recipient", "Tìm người nhận"),
    "btnHstMMFinish": ("Finish & Merge", "Hoàn tất và trộn"),
}
# caption context -> (English source, new Vietnamese)
CAPTIONS = {"labelMailingsStart": ("Start Mail Merge", "Bắt đầu trộn thư"),
            "labelMailingsHstFields": ("Write & Insert Fields", "Soạn và chèn trường"),
            "labelMailingsHstPreview": ("Preview Results", "Xem trước kết quả"),
            "labelMailingsFinish": ("Finish", "Hoàn tất")}
DESCRIPTION = """HST Office: the Writer "Gửi thư" tab follows the familiar step-by-step mail merge (generated).

Generated by scripts/patches/generate-mail-merge-ribbon.py. Groups Bắt đầu trộn thư (Chọn người nhận, Sửa danh sách
người nhận, Trình hướng dẫn trộn thư (đầy đủ)), Soạn và chèn trường (Chèn trường trộn, Định dạng trường, Field
Shadings), Xem trước kết quả (Xem trước kết quả, Bản ghi đầu/trước/sau/cuối, Tìm người nhận, "Bản ghi n / N") and Hoàn tất (Hoàn
tất và trộn) run the HST Trộn thư commands (org.hst.office.mailmerge:, extension hst-vietnamese-tools). The "Tạo"
group is unchanged. Group and caption ids are kept; the Vietnamese strings are added to sw/messages.po.

License: these upstream files remain under their original license (MPL-2.0).
---
"""


def b(name, command, icon="", tip=False):
    return button(name, command, STRINGS[name][0], icon, STRINGS[name + "Tip"][0] if tip else "")


def groups():
    start = [cell(toolbox("bxHstMMRecipients", [b("btnHstMMRecipients", "Recipients", "cmd/lc_dbviewtables.png", True)],
                          "both", big=True), 0, 0, height=2),
             cell(toolbox("bxHstMMEditRecipients", [b("btnHstMMEditRecipients", "EditRecipients", "cmd/sc_dbqueryedit.png")],
                          "both-horiz"), 1, 0),
             cell(toolbox("bxHstMMWizard", [b("btnHstMMWizard", "Wizard", "cmd/sc_mailmergewizard.png")], "both-horiz"), 1, 1)]
    fields = [cell(toolbox("bxHstMMInsertField", [b("btnHstMMInsertField", "InsertField", "cmd/lc_insertfieldctrl.png")],
                           "both", big=True), 0, 0, height=2),
              cell(toolbox("bxHstMMFieldFormat", [b("btnHstMMFieldFormat", "FieldFormat", "cmd/sc_numberformatstandard.png")],
                           "both-horiz"), 1, 0),
              cell(_marks(), 1, 1)]
    nav = hbox("boxHstMMNav", [
        toolbox("bxHstMMNav", [b("btnHstMMFirst", "First", "cmd/sc_firstrecord.png"),
                               b("btnHstMMPrev", "Prev", "cmd/sc_prevrecord.png"),
                               b("btnHstMMNext", "Next", "cmd/sc_nextrecord.png"),
                               b("btnHstMMLast", "Last", "cmd/sc_lastrecord.png")], "icons"),
        toolbox("bxHstMMFind", [b("btnHstMMFind", "Find", "cmd/sc_recsearch.png")], "both-horiz")])
    # the record text has a row of its own: the cell is as wide as the row above, so "Bản ghi 12 / 150" fits
    preview = [cell(toolbox("bxHstMMPreview", [b("btnHstMMPreview", "Preview", "cmd/lc_printpreview.png")], "both", big=True),
                    0, 0, height=2),
               cell(nav, 1, 0),
               cell(toolbox("bxHstMMRecord", [b("btnHstMMRecord", "Record")], "text"), 1, 1)]
    finish = [cell(toolbox("bxHstMMFinish", [b("btnHstMMFinish", "Finish", "cmd/lc_mailmergecreatedocuments.png")],
                           "both", big=True), 0, 0, height=2)]
    return (group("gdMailingsStart", "lbMailingsStart", "labelMailingsStart", CAPTIONS["labelMailingsStart"][0], start, 2, 1)
            + group("gdMailingsHstFields", "lbMailingsHstFields", "labelMailingsHstFields",
                    CAPTIONS["labelMailingsHstFields"][0], fields, 2, 2)
            + group("gdMailingsHstPreview", "lbMailingsHstPreview", "labelMailingsHstPreview",
                    CAPTIONS["labelMailingsHstPreview"][0], preview, 2, 3)
            + group("gdMailingsFinish", "lbMailingsFinish", "labelMailingsFinish", CAPTIONS["labelMailingsFinish"][0],
                    finish, 1, 4))


def _marks():
    """Field shadings stay the core command (its label and check state come from the command)."""
    return ('<object class="sfxlo-NotebookbarToolBox" id="bxHstMergeMarks">\n  <property name="visible">True</property>\n'
            '  <property name="can-focus">False</property>\n  <property name="toolbar-style">both-horiz</property>\n'
            '  <property name="show-arrow">False</property>\n  <child>\n'
            '    <object class="GtkToolButton" id="btnHstMergeMarks">\n      <property name="visible">True</property>\n'
            '      <property name="can-focus">False</property>\n      <property name="action-name">.uno:Marks</property>\n'
            '    </object>\n    <packing>\n      <property name="expand">False</property>\n'
            '      <property name="homogeneous">False</property>\n    </packing>\n  </child>\n</object>')


def new_ui(text):
    first = text.index('<object class="GtkGrid" id="gdMailingsStart">')
    begin = text.rindex("\n", 0, text.rindex("<child>", 0, first)) + 1
    finish = text.index('<object class="GtkGrid" id="gdMailingsFinish">')
    end = text.index("</child>\n", text.index('<property name="position">4</property>', finish)) + len("</child>\n")
    return text[:begin] + groups() + text[end:]


def new_po(text):
    for context, (source, vietnamese) in CAPTIONS.items():
        head = 'msgctxt "TabbedWriter|%s"\nmsgid "%s"\nmsgstr "' % (context, source)
        start = text.index(head) + len(head)
        text = text[:start] + vietnamese + text[text.index('"\n', start):]
    anchor = 'msgctxt "TabbedWriter|labelMailingsHstPreview"\nmsgid "Preview Results"\nmsgstr "Xem trước kết quả"\n'
    entries = "".join('\n#. hstMM\n#: sw/uiconfig/swriter/ui/notebookbar.ui\nmsgctxt "TabbedWriter|%s"\nmsgid "%s"\nmsgstr "%s"\n'
                      % (context, source, vietnamese) for context, (source, vietnamese) in STRINGS.items())
    at = text.index(anchor) + len(anchor)
    return text[:at] + entries + text[at:]


def diff(path, old, new):
    lines = difflib.unified_diff(old.splitlines(True), new.splitlines(True), "a/" + path, "b/" + path, n=3)
    return "".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--tree", required=True)
    parser.add_argument("--out", default=OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    patch = DESCRIPTION
    for path, change in ((UI, new_ui), (PO, new_po)):
        with open(os.path.join(args.tree, path), encoding="utf-8") as handle:
            old = handle.read()
        patch += diff(path, old, change(old))
    if args.check:
        with open(args.out, encoding="utf-8") as handle:
            same = handle.read() == patch
        print("up to date" if same else "OUT OF DATE: %s" % args.out)
        return 0 if same else 1
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(patch)
    print("wrote", args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
