# --- the patch ---------------------------------------------------------------------------------------------

def build(tree, path, app):
    old = L.read(tree, path)
    root = L.parse_text(old)
    b = Builder(root, app)
    (edit_impress if app == "impress" else edit_draw)(b)
    b.renumber()
    prune_empty_toolboxes(root, b.emptied)
    L.check_unique(root)
    return old, L.serialize_like(old, root), root, b.strings


def prune_empty_toolboxes(root, emptied):
    """Remove the toolboxes left without a button by the edits (not the ones empty before)."""
    for box in list(root.iter("object")):
        if box.get("class") == BOX and box.get("id") in emptied and not any(c.tag == "child" for c in box):
            L.remove(root, box)


MENU_ITEMS = ("GtkMenuItem", "GtkCheckMenuItem", "GtkRadioMenuItem")


def minimal_suppr(old, ui_path, root):
    """The .suppr with this file's button-no-label lines for the current unlabelled toolbox and menu items: lines
    of items that are gone or changed class are dropped, new ones go after the file's last line (keeps the diff
    small; gla11y also checks menu items, whose command names them)."""
    wanted = set(L.unlabelled_buttons(root)) | {
        (o.get("class"), o.get("id")) for o in root.iter("object")
        if o.get("class") in MENU_ITEMS and o.get("id") and not any(p.get("name") == "label" for p in o.findall("property"))}

    def key(line):
        klass = line.split("://", 1)[1].split("[", 1)[0]
        return klass, line.split("@id='")[1].split("'")[0]
    lines = old.splitlines(keepends=True)
    mine = [i for i, line in enumerate(lines) if line.startswith(ui_path + ":")]
    is_label_line = lambda line: line.startswith(ui_path + ":") and line.rstrip().endswith("button-no-label")  # noqa: E731
    kept = [line for line in lines if not (is_label_line(line) and key(line) not in wanted)]
    listed = {key(line) for line in kept if is_label_line(line)}
    new = [f"{ui_path}://{klass}[@id='{oid}'] button-no-label\n" for klass, oid in sorted(wanted - listed,
           key=lambda item: [o.get("id") for o in root.iter("object")].index(item[1]))]
    if not mine:
        return "".join(kept + new)
    last = lines[mine[-1]]
    at = kept.index(last) + 1 if last in kept else len(kept)
    return "".join(kept[:at] + new + kept[at:])


def patch_text(tree):
    diffs, strings = [], {}
    roots = {}
    for path, app in ((IMPRESS_UI, "impress"), (DRAW_UI, "draw")):
        old, new, root, found = build(tree, path, app)
        diffs.append(L.file_diff(path, old, new))
        roots[path] = root
        strings.update(found)
    for suppr_path, ui_path in ((IMPRESS_SUPPR, IMPRESS_UI), (DRAW_SUPPR, DRAW_UI)):
        old = L.read(tree, suppr_path)
        new = minimal_suppr(old, ui_path, roots[ui_path])
        if new != old:
            diffs.append(L.file_diff(suppr_path, old, new))
    po_old = L.read(tree, VI_PO)
    rows = sorted((context, msgid, msgstr) for (context, msgid), msgstr in strings.items())
    po_new = L.po_with_entries(po_old, IMPRESS_UI, rows, PO_ANCHOR)
    diffs.append(L.file_diff(VI_PO, po_old, po_new))
    return diffs, rows


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tree", required=True)
    parser.add_argument("--out", default=OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        diffs, _rows = patch_text(args.tree)
    except (L.RibbonUxError, OSError, ValueError) as error:
        print(f"cannot generate the Slides/Draw ribbon rework: {error}", file=sys.stderr)
        return 2
    return L.write_patch(args.out, DESCRIPTION, diffs, check=args.check)


if __name__ == "__main__":
    sys.exit(main())
