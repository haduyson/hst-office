"""Generate the uniform group layout of the four HST ribbons (patches/libreoffice/hst-ribbon-ux-uniform-layout.patch).

Usage: scripts/patches/generate-ribbon-ux-uniform.py --tree DIR [--out PATCH] [--check]

DIR is a LibreOffice tree with the series applied up to (not including) this patch: every patch that edits the
Tabbed notebookbar.ui of Writer, Sheets, Slides and Draw comes before it, so the rules of ribbon_layout_rules.py
hold on what the user sees, whichever patch placed a group:
- a group of at most three commands (no control) gets one large button per command, filling its height;
- in the other groups a small one-command button alone in its column (or floating in a cell of both rows)
  becomes a large button filling the group's height.
Only packing and size properties change: ids, labels and commands stay, so key tips, ladders and the
accessibility suppressions are not affected. The output is byte-stable; --check only compares it.
"""
import argparse
import os
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ribbon_layout_rules as R  # noqa: E402
import ribbon_ux_lib as L  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "patches", "libreoffice", "hst-ribbon-ux-uniform-layout.patch")
DESCRIPTION = """HST Office: one layout rule for every ribbon group of Writer, Sheets, Slides and Draw (generated).

Generated by scripts/patches/generate-ribbon-ux-uniform.py (rules: scripts/patches/ribbon_layout_rules.py), after
the owner decision of 13/11/2026: groups with few commands use large buttons filling the group's height, so the
groups look alike; small two-row stacks only in groups with many commands, without a small button alone in its
column. In the Tabbed notebookbar.ui of the four apps:
- a group of one to three commands (no combo box, find box or gallery) shows each command as a large button
  (big icon, label under it), one per column; a group whose caption sat in row 1 gets it under the two rows;
- in the other groups a small one-command button alone in its column becomes a large button.
Only packing and size properties change (ids, labels, commands, key tips and ladders stay); the ladder keeps
the few-command groups large at every width (hst-ribbon-ux-few-command-groups.patch).
The check scripts/patches/check-ribbon-layout.py verifies these rules on a tree with the whole series."""

BIG_TOOLBOX = (("valign", "center"), ("vexpand", "True"), ("toolbar-style", "both"), ("show-arrow", "False"),
               ("icon_size", "3"))


def set_packing(item, left=None, top=None, height=None, width=None):
    pack = item.hold.find("packing")
    if pack is None:
        pack = ET.SubElement(item.hold, "packing")
    for name, value in (("left-attach", left), ("top-attach", top)):
        if value is not None:
            L.set_prop(pack, name, str(value))
    for name, value in (("height", height), ("width", width)):
        if value is not None:
            L.set_prop(pack, name, None if value == 1 else str(value))


def make_big(item):
    obj = item.obj
    if item.kind == "toolbox":
        for name, _ in BIG_TOOLBOX:
            L.set_prop(obj, name, None)
        for name, value in BIG_TOOLBOX:
            L.set_prop(obj, name, value)
    elif item.kind == "menu":
        if L.prop(obj, "image"):
            L.set_prop(obj, "image-position", "top")
        L.set_prop(obj, "valign", "center")
        L.set_prop(obj, "vexpand", "True")


def one_row_of_large_buttons(group):
    """Each command its own column of large buttons; the caption under them, the separator after them."""
    items = sorted(group.items, key=lambda item: (item.left, item.top))
    for left, item in enumerate(items):
        make_big(item)
        set_packing(item, left=left, top=0, height=2, width=1)
    if group.caption is not None:
        pack = group.caption.find("packing")
        L.set_prop(pack, "left-attach", "0")
        L.set_prop(pack, "top-attach", "2")
        L.set_prop(pack, "width", None if len(items) == 1 else str(len(items)))
    for hold in group.grid.findall("child"):
        obj = hold.find("object")
        if obj is not None and obj.get("class") == "GtkSeparator":
            pack = hold.find("packing")
            L.set_prop(pack, "left-attach", str(len(items)))
            L.set_prop(pack, "top-attach", "0")
            L.set_prop(pack, "height", "3")


def apply_rules(root):
    """Edit root in place; returns the number of groups changed."""
    changed = 0
    for group in R.groups(root):
        if not R.violations(group):
            continue
        changed += 1
        if group.few:
            one_row_of_large_buttons(group)
            continue
        for item in group.items:
            if R.lone(group, item):
                make_big(item)
                set_packing(item, top=0, height=2)
    left = R.check_root(root)
    if left:
        raise L.RibbonUxError("rules still broken after the fix: " + ", ".join(f"{g.id} {r}" for g, r, _, _ in left))
    return changed


def patch_text(tree):
    diffs = []
    for path in R.RIBBONS.values():
        old = L.read(tree, path)
        root = L.parse_text(old)
        if apply_rules(root):
            diffs.append(L.file_diff(path, old, L.serialize_like(old, root)))
    return diffs


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tree", required=True)
    parser.add_argument("--out", default=OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        diffs = patch_text(args.tree)
    except (L.RibbonUxError, OSError, ValueError) as error:
        print(f"cannot generate the uniform ribbon layout: {error}", file=sys.stderr)
        return 2
    return L.write_patch(args.out, DESCRIPTION, diffs, check=args.check)


if __name__ == "__main__":
    sys.exit(main())
