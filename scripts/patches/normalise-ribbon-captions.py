"""Generate the patch that gives every ribbon group the same caption style and outer margins.

Usage: scripts/patches/normalise-ribbon-captions.py --tree DIR
           [--out patches/libreoffice/hst-ribbon-caption-style.patch] [--check]

DIR is a LibreOffice tree with the series applied up to (not including) the generated patch, e.g. the output of
a fresh apply. For the groups of the merged group boxes (sfx2 PriorityMergedHBox) of the Tabbed notebookbar.ui of
Writer, Sheets and Slides:
  - the caption (the label the group is labelled by, else the label in the group's last row) is upright at 0.9
    scale, as the Home tabs show it: the italic and thin captions of the other tabs go;
  - the group grid has the outer margins of the Home tabs' groups: 4 px start, 2 px end, 6 px top and bottom.
Spacing inside the groups (rows, columns) and the 2-row bodies stay as authored. The edits are made on the text,
so the rest of each file is untouched; the output is byte-stable; --check only compares with the existing patch.
"""
import argparse
import difflib
import os
import re
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
UI = ("sw/uiconfig/swriter/ui/notebookbar.ui", "sc/uiconfig/scalc/ui/notebookbar.ui",
      "sd/uiconfig/simpress/ui/notebookbar.ui")
MARGINS = (("margin-start", "4"), ("margin-end", "2"), ("margin-top", "6"), ("margin-bottom", "6"))
CAPTION_ATTRIBUTES = (("style", "normal"), ("scale", "0.9"))
OUT = os.path.join(ROOT, "patches", "libreoffice", "hst-ribbon-caption-style.patch")
DESCRIPTION = """HST Office: every ribbon group has the same caption style and outer margins (generated).

Generated by scripts/patches/normalise-ribbon-captions.py from the Tabbed notebookbar.ui of Writer, Sheets
and Slides. The groups of the merged group boxes had italic, upright or thin captions and five different
pairs of outer margins, so the tabs looked uneven and the space between groups varied. Every caption is now
upright at 0.9 scale, as on the Home tabs, and every group grid has the Home groups' outer margins (4 px
start, 2 px end, 6 px top and bottom). Spacing inside the groups and their 2-row bodies stay as authored.

License: these upstream files remain under their original license (MPL-2.0).
---
"""


class CaptionError(Exception):
    pass


def groups(text):
    """[(grid id, caption label id)] of the groups of every merged group box, in file order."""
    root = ET.fromstring(text)
    found = []
    for box in root.iter("object"):
        if box.get("class") != "sfxlo-PriorityMergedHBox":
            continue
        for child in box.findall("child"):
            grid = child.find("object")
            if grid is None or grid.get("class") != "GtkGrid":
                continue
            found.append((grid.get("id"), caption(grid)))
    return found


def caption(grid):
    """The id of the group's caption: the labelled-by target, else the label in the last row."""
    for relation in grid.findall("accessibility/relation"):
        if relation.get("type") == "labelled-by":
            return relation.get("target")
    best, bottom = None, -1
    for child in grid.findall("child"):
        obj = child.find("object")
        if obj is None:
            continue
        packing = {p.get("name"): int(p.text) for p in child.findall("packing/property")
                   if p.get("name") in ("top-attach", "height")}
        row = packing.get("top-attach", 0) + packing.get("height", 1)
        labels = [obj] if obj.get("class") == "GtkLabel" else [o for o in obj.iter("object") if o.get("class") == "GtkLabel"]
        if labels and row > bottom:
            best, bottom = labels[0].get("id"), row
    return best


def object_span(lines, object_id):
    """(first line, line of its first <child>/<attributes>/</object>) of <object ... id="object_id">."""
    pattern = re.compile(r'<object class="[^"]+" id="%s">' % re.escape(object_id))
    starts = [i for i, line in enumerate(lines) if pattern.search(line)]
    if len(starts) != 1:
        raise CaptionError(f"object {object_id}: {len(starts)} matches")
    start = starts[0]
    end = start + 1
    while not re.match(r"\s*<(child|attributes|accessibility|/object|style)\b", lines[end]):
        end += 1
    return start, end


def set_margins(lines, grid_id):
    start, end = object_span(lines, grid_id)
    indent = re.match(r"\s*", lines[start + 1]).group(0)
    props = lines[start + 1:end]
    for name, value in MARGINS:
        new = f'{indent}<property name="{name}">{value}</property>\n'
        index = next((i for i, line in enumerate(props) if f'<property name="{name}">' in line), None)
        if index is None:
            # after the last of visible/can-focus/margin-* so the order stays as the other groups'
            anchor = max(i for i, line in enumerate(props)
                         if re.search(r'<property name="(visible|can-focus|margin-[a-z]+)">', line))
            props.insert(anchor + 1, new)
        else:
            props[index] = new
    lines[start + 1:end] = props


def set_caption(lines, label_id):
    start, _end = object_span(lines, label_id)
    close = next(i for i in range(start, len(lines)) if "</object>" in lines[i] or "<child>" in lines[i])
    attr_start = next((i for i in range(start, close) if "<attributes>" in lines[i]), None)
    if attr_start is None:
        raise CaptionError(f"caption {label_id}: no <attributes>")
    attr_end = next(i for i in range(attr_start, close) if "</attributes>" in lines[i])
    indent = re.match(r"\s*", lines[attr_start + 1]).group(0)
    lines[attr_start + 1:attr_end] = [f'{indent}<attribute name="{name}" value="{value}"/>\n'
                                      for name, value in CAPTION_ATTRIBUTES]


def normalise(text):
    lines = text.splitlines(keepends=True)
    for grid_id, label_id in groups(text):
        if not grid_id:
            raise CaptionError("a group grid without id")
        set_margins(lines, grid_id)
        if label_id:
            set_caption(lines, label_id)
    return "".join(lines)


def patch_text(tree):
    parts = [DESCRIPTION]
    for path in UI:
        with open(os.path.join(tree, path), encoding="utf-8") as handle:
            old = handle.read()
        new = normalise(old)
        parts.extend(difflib.unified_diff(old.splitlines(keepends=True), new.splitlines(keepends=True),
                                          f"a/{path}", f"b/{path}", n=3))
    return "".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tree", required=True)
    parser.add_argument("--out", default=OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = patch_text(args.tree)
    if args.check:
        with open(args.out, encoding="utf-8") as handle:
            if handle.read() != text:
                print(f"stale: {args.out}", file=sys.stderr)
                return 1
        print(f"ok: {args.out}")
        return 0
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
