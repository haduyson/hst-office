"""The Home tab's Tools button drops its caption only before Paragraph collapses (hst-ribbon-tools-bare.patch,
hst-ribbon-tools-bare-ladders.patch generated by scripts/patches/generate-ribbon-blocks.py). Reads patches only."""
import copy
import importlib.util
import json
import os
import tempfile
import unittest

from _paths import ROOT
from test_ribbon_group_button import added

spec = importlib.util.spec_from_file_location("generate_ribbon_blocks", os.path.join(ROOT, "scripts/patches/generate-ribbon-blocks.py"))
gen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gen)
DATA = json.load(open(os.path.join(ROOT, "data/ribbon/scaling-ladders.json"), encoding="utf-8"))
PATCHES = os.path.join(ROOT, "patches", "libreoffice")
BARE = os.path.join(PATCHES, "hst-ribbon-tools-bare.patch")
TABLE = os.path.join(PATCHES, "hst-ribbon-tools-bare-ladders.patch")


def fixture_tree(tmp, data):
    for ladder in data["ladders"]:
        children = "".join(f'<child><object class="GtkGrid" id="{g}"/></child>' for g in ladder["groups"])
        path = os.path.join(tmp, gen.scale.UI[ladder["app"]])
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(f'<interface><object class="sfxlo-PriorityMergedHBox" id="{ladder["box"]}">{children}</object></interface>')
    return tmp


class BlocksTable(unittest.TestCase):
    def test_committed_patch_is_current(self):
        with tempfile.TemporaryDirectory() as tmp:
            gen.validate(DATA, fixture_tree(tmp, DATA))
        with open(TABLE, encoding="utf-8") as handle:
            self.assertEqual(handle.read(), gen.patch_text(gen.header(DATA)))

    def test_paragraph_in_writer_and_slides_only(self):
        named = {l["app"]: l.get("bare_block_before") for l in DATA["ladders"]}
        self.assertEqual(named, {"writer": "gdHomeParagraph", "calc": None, "impress": "gdHomeParagraph"})

    def test_the_named_group_must_collapse(self):
        data = copy.deepcopy(DATA)
        data["ladders"][0]["bare_block_before"] = "gdHomeFont"  # Font has no C step
        with tempfile.TemporaryDirectory() as tmp:
            with self.assertRaises(gen.scale.LadderError):
                gen.validate(data, fixture_tree(tmp, data))


class ToolsBare(unittest.TestCase):
    def test_bare_only_when_it_keeps_the_group(self):
        merged = added(BARE, "vcl/source/control/PriorityMergedHBox.cxx")
        self.assertIn("bool PriorityMergedHBox::HstBlockShouldBeBare(tools::Long nRoom, tools::Long nGain) const", merged)
        self.assertIn("return !kept(nRoom) && kept(nRoom + nGain);", merged)
        self.assertIn("#include <HstRibbonBlocks.hxx>", merged)
        # planning reuses the ladder's own pass that brings collapsed groups back
        self.assertEqual(merged.count("lcl_HstUncollapse("), 3)

    def test_caption_stays_tooltip_and_name(self):
        dropdown = added(BARE, "vcl/source/control/DropdownBox.cxx")
        self.assertIn("void DropdownBox::HstSetBare(bool bBare)", dropdown)
        self.assertIn('m_pButton->SetText(bBare ? u"\\u25BE"_ustr', dropdown)
        self.assertNotIn("SetAccessibleName(u", dropdown)
        self.assertNotIn("SetQuickHelpText(u", dropdown)

    def test_asked_after_the_block_collapsed(self):
        prio = added(BARE, "vcl/source/control/PriorityHBox.cxx")
        self.assertIn("pBlock->HstIsCollapsed()", prio)
        self.assertIn("pMerged->HstBlockShouldBeBare(nRoom, nCaption - pBlock->HstButtonWidth(true))", prio)
        self.assertIn("pBlock->HstSetBare(bBare);", prio)


if __name__ == "__main__":
    unittest.main()
