"""The Writer part of the ribbon UX rework (hst-ribbon-ux-writer.patch and hst-ribbon-ux-writer-commands.patch,
generated by scripts/patches/generate-ribbon-ux-writer.py). Reads the patches and the generator's data; the
byte-stability check runs when HST_RIBBON_UX_TREE names a tree with the series applied before these patches."""
import importlib.util
import os
import re
import subprocess
import sys
import unittest

from _paths import ROOT

PATCHES = os.path.join(ROOT, "patches", "libreoffice")
GENERATOR = os.path.join(ROOT, "scripts", "patches", "generate-ribbon-ux-writer.py")
sys.path.insert(0, os.path.dirname(GENERATOR))
spec = importlib.util.spec_from_file_location("generate_ribbon_ux_writer", GENERATOR)
gen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gen)
import ribbon_ux_writer_strings as strings  # noqa: E402
import ribbon_ux_writer_tabs as tabs  # noqa: E402
import ribbon_ux_writer_tips as tips  # noqa: E402

FORBIDDEN = re.compile(r"[Vv]ĩ lệnh|[Pp]hối thư|\bBasic\b|Microsoft|\bWord\b|\bExcel\b|PowerPoint|\bOffice\b|&")


def read(name):
    with open(os.path.join(PATCHES, name), encoding="utf-8") as handle:
        return handle.read()


def section(text, path):
    start = text.index(f"+++ b/{path}\n")
    end = text.find("\n--- a/", start)
    return text[start:end if end >= 0 else len(text)]


def added(text):
    return "\n".join(line[1:] for line in text.splitlines() if line.startswith("+") and not line.startswith("+++"))


def all_texts():
    pairs = list(strings.LABELS.values()) + list(strings.CAPTIONS.values()) + list(tips.DESCRIPTIONS.values())
    for entries in strings.MENUS.values():
        stack = list(entries)
        while stack:
            entry = stack.pop()
            if isinstance(entry, tuple):
                if entry[1]:
                    pairs.append(entry[1])
                stack.extend(entry[2] if len(entry) > 2 else [])
    for spec_ in tabs.GROUPS.values():
        if "new" in spec_:
            pairs.append(spec_["new"])
    return pairs


class RibbonUxWriterPatch(unittest.TestCase):
    patch = read("hst-ribbon-ux-writer.patch")
    commands = read("hst-ribbon-ux-writer-commands.patch")

    def test_files(self):
        for path in (gen.UI, gen.PO, gen.SUPPR):
            self.assertIn(f"+++ b/{path}\n", self.patch)
        for path in ("Controller.xcu", "sw/UIConfig_swriter.mk", "popupmenu/hstpaste.xml",
                     "popupmenu/hstcitationinsert.xml"):
            self.assertIn(path, self.commands)

    def test_terms(self):
        for english, vietnamese in all_texts():
            self.assertNotRegex(vietnamese, FORBIDDEN, english)
            self.assertNotRegex(english, r"Microsoft|\bWord\b|\bExcel\b|PowerPoint", english)
            self.assertFalse(vietnamese.endswith(("…", "...")), vietnamese)
        ui = added(section(self.patch, gen.UI))
        self.assertNotRegex(ui, r"[Vv]ĩ lệnh|[Pp]hối thư")

    def test_every_string_is_translated(self):
        po = added(section(self.patch, gen.PO))
        ui = added(section(self.patch, gen.UI))
        for context, msgid in set(re.findall(r'context="(TabbedWriter\|hstUx\w+)">([^<]+)<', ui)):
            msgid = msgid.replace("&#10;", "\\n")
            self.assertRegex(po, re.escape(f'msgctxt "{context}"\nmsgid "{msgid}"\nmsgstr "') + r'[^"]+"', msgid)

    def test_home_tab(self):
        self.assertEqual(tabs.TABS["pmhbHome"][-2:], ["gdHomeHstEditing", "gdHomeHstVietnamese"])
        self.assertEqual(tabs.GROUPS["gdHomeHstVietnamese"]["new"][1], "Tiện ích Việt")
        ui = added(section(self.patch, gen.UI))
        for command in ("org.hst.office.vi:Nd30Wizard", "org.hst.office.vi:ConvertEncoding",
                        "org.hst.office.vi:NumberToWords", "vnd.sun.star.findbar:FocusToFindbar"):
            self.assertIn(f'"action-name">{command}<', ui)
        self.assertIn("Home-Menu", tabs.BLOCKS)

    def test_citations_group(self):
        self.assertEqual(tabs.TABS["pmhbReferences"], ["gdReferencesIndex", "gdReferencesReference",
                                                       "gdReferencesHstCitations", "gdReferencesCaptions"])
        ui = added(section(self.patch, gen.UI))
        order = re.findall(r'"action-name">org\.hst\.office\.vi:(Citation\w+)<', ui)
        self.assertEqual(order, ["CitationInsert", "CitationReinsert", "CitationBibliography", "CitationStyle",
                                 "CitationUpdate", "CitationLibrary"])
        self.assertIn('class="GtkMenuToolButton" id="btnReferencesHstCitationInsert"', ui)
        self.assertNotIn(".uno:BibliographyComponent", ui)
        popup = section(self.commands, "sw/uiconfig/swriter/popupmenu/hstcitationinsert.xml")
        self.assertIn('menu:label="Thêm nguồn mới"', popup)
        self.assertIn("org.hst.office.vi:CitationInsert", section(self.commands, gen.commands.CONTROLLER))

    def test_extension_tab_keeps_its_name_and_gathers_developer_tools(self):
        self.assertEqual(tabs.TABS["pmhbExtension"][0], "gdExtensionHstVietnamese")
        self.assertEqual(tabs.TABS["pmhbExtension"][-2:], ["gdToolsMacro", "Extension"])
        self.assertEqual(strings.CAPTIONS["gdToolsMacro"], ("Developer", "Nhà phát triển"))
        self.assertEqual(strings.LABELS["btnToolsMacroDialog"][1], "Quản lý macro")
        self.assertNotRegex(section(self.patch, gen.UI), r'(?m)^[-+].*id="ExtensionLabel"')

    def test_no_trailing_blocks(self):
        ui = section(self.patch, gen.UI)
        removed = set(re.findall(r'^-\s*<object class="sfxlo-DropdownBox" id="([^"]+)"', ui, re.M))
        self.assertEqual(removed, set(tabs.BLOCKS))
        self.assertNotIn("+                  <object class=\"sfxlo-DropdownBox\"", ui)

    def test_accessibility(self):
        suppr = added(section(self.patch, gen.SUPPR))
        self.assertIn("GtkMenuItem[@id='MenuHstHomeSelect-0'] button-no-label", suppr)
        ui = added(section(self.patch, gen.UI))
        for label in ("txtLayoutHstIndent", "txtLayoutHstSpacing"):
            self.assertEqual(ui.count(f'<relation type="labelled-by" target="{label}"/>'), 2, label)

    def test_page_border_and_margin_preset(self):
        ui = added(section(self.patch, gen.UI))
        self.assertIn('"action-name">.uno:BorderDialog?Page:string=hstpageborder<', ui)
        self.assertIn("(SfxStringItem Page FN_PARAM_1)", section(self.commands, "sw/sdi/swriter.sdi"))
        self.assertIn('SetCurPageId(rPage)', section(self.commands, "sw/source/ui/frmdlg/uiborder.cxx"))
        margins = section(self.commands, "sw/source/uibase/sidebar/PageMarginControl.hxx")
        for value in ("toTwips(30, o3tl::Length::mm)", "toTwips(15, o3tl::Length::mm)", "toTwips(20, o3tl::Length::mm)"):
            self.assertIn(value, margins)
        self.assertIn('id="hstnd30"', section(self.commands, "sw/uiconfig/swriter/ui/pagemargincontrol.ui"))
        self.assertIn('msgid "Administrative Document"\n+msgstr "Văn bản hành chính"', section(self.patch, gen.PO))

    def test_tab_labels_use_va(self):
        po = section(self.patch, gen.PO)
        self.assertIn('msgid "~Header and Footer"\n+msgstr "Đầu trang và c~hân trang"', po)
        for _english, vietnamese in strings.TAB_LABELS.values():
            self.assertNotIn("&", vietnamese)

    def test_groups_use_va(self):
        for english, vietnamese in strings.CAPTIONS.values():
            self.assertNotIn("&", vietnamese + english)

    def test_left_ribbon_is_documented(self):
        self.assertEqual(gen.LEFT_RIBBON, {".uno:HelplinesMove", ".uno:IncrementLevel", ".uno:InsertAuthoritiesEntry",
                                           ".uno:InsertDraw", ".uno:InsertPageCountField", ".uno:InsertPageNumberField",
                                           ".uno:InsertSection", ".uno:InsertTitleField", ".uno:TableBoundaries"})

    @unittest.skipUnless(os.environ.get("HST_RIBBON_UX_TREE"), "HST_RIBBON_UX_TREE not set")
    def test_generator_is_byte_stable(self):
        result = subprocess.run([sys.executable, GENERATOR, "--tree", os.environ["HST_RIBBON_UX_TREE"], "--check"],
                                capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)


if __name__ == "__main__":
    unittest.main()
