"""The dialogs of the HST coat's tier 3 (dialog layout rework): candidates, the ranked list and its batches.

Shared by tests/runtime/hst_dialog_layout_check.py (opens each dialog and measures it) and
tests/unit/test_ui_layout_rulebook.py (every .ui of the list belongs to exactly one batch). The ranking itself, with
its evidence, is in plans/261120-0850-hst-ui-coat-tier2-3/reports/dialog-inventory.{md,json}.

Each candidate: id -> Case(batch, English name, document factory, command that opens it (None: no route without a
user's file or a click deep inside another dialog; measured statically only), setup recipe, the .ui files the batch
owns (dialog shell first, then its own tab pages), .ui files it shows but another case owns, extra commands that
open the same dialog (scored too), tab pages to visit (True: every tab)).

Batches: A Writer and the text/page/border/area pages shared by all apps (cui); B Sheets and charts; C Slides, Draw
and shapes; D app-wide. A shared page belongs to one batch only; the others measure it and report to its owner.
A batch may add cases of its own in tests/runtime/data/dialog-layout-<a|b|c|d>.json (same fields, see load_extra).
"""
