def load_extra(directory=os.path.join(os.path.dirname(os.path.abspath(__file__)), "data")):
    """Cases a batch adds in tests/runtime/data/dialog-layout-<batch>.json: {"id": {"en", "factory", "command",
    "setup", "ui", "uses", "aliases", "tabs"}}; the batch is taken from the file name."""
    extra = {}
    if not os.path.isdir(directory):
        return extra
    for name in sorted(os.listdir(directory)):
        if not (name.startswith("dialog-layout-") and name.endswith(".json")):
            continue
        batch = name[len("dialog-layout-"):-len(".json")].upper()
        with open(os.path.join(directory, name), encoding="utf-8") as handle:
            for key, value in json.load(handle).items():
                if key in CANDIDATES or key in extra:
                    raise ValueError(f"{name}: case {key} already defined")
                extra[key] = case(batch, value["en"], value["factory"], value.get("command"), value["ui"],
                                  value.get("uses", ()), value.get("aliases", ()), value.get("setup"),
                                  value.get("tabs", False))
    return extra


def listed():
    """{id: Case} of the ranked list plus the batches' own additions."""
    cases = {key: CANDIDATES[key] for key in LIST}
    cases.update(load_extra())
    return cases
