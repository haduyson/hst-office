def language(ctx):
    """"en" when the office UI is English, else "vi"."""
    try:
        from .ui_language import _node
        locale = _node(ctx, "/org.openoffice.Setup/L10N").getPropertyValue("ooLocale") or ""
    except Exception:  # noqa: BLE001 - no configuration: Vietnamese
        locale = ""
    return "en" if locale.lower().startswith("en") else "vi"


def texts(ctx):
    return EN if language(ctx) == "en" else VI
