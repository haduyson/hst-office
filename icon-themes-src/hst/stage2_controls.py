    add('filecontrol',r(2,5,20,14,1)+p('M16 5v14M4 10h9m-9 4h7M18 12h2'),'File path field and browse button')
    add('imagecontrol',r(2,2,20,20)+p('M6 17l4-5 4 3 4-6')+c(7,7,1),'Image form control')
    add('imagebutton',r(2,5,20,14,3)+p('m5 15 4-5 5 5 4-5')+c(6,8,.7),'Rounded image button')
    add('navigationbar',r(2,6,20,12,1)+p('M5 9v6m5-6-3 3 3 3m4-6 3 3-3 3M19 9v6'),'Form record navigation bar')
    add('autocontrolfocus',p('M3 8V3h5m8 0h5v5M3 16v5h5m8 0h5v-5')+c(12,12,3),'Focus target inside corner brackets')
    add('controlproperties',badge(r(3,5,18,12,2)+p('M7 11h10'),transform(gear(),'translate(10 10) scale(.55)')),'Control properties gear')
    add('formproperties',badge(page()+r(8,7,8,4)+r(8,14,8,4),transform(gear(),'translate(10 10) scale(.55)')),'Form properties gear')
    add('showfmexplorer',p('M3 3v18M3 6h5m-5 6h5m-5 6h5')+r(9,3,12,5)+r(9,10,12,5)+r(9,17,12,5),'Form navigator tree')
    add('switchcontroldesignmode',badge(r(3,4,18,16)+r(6,8,12,5),small_pen()),'Form design pencil')
    add('advancedmode',badge(r(3,4,18,16)+p('M6 8h9M6 12h9'),p('M13 20h8m-3-3 3 3-3 3')),'Edit mode pointer')
    add('basicideappear',r(2,3,20,18,1)+p('M2 7h20m-13 4-4 3 4 3m6-6 4 3-4 3'),'Code editor window')
    add('runmacro',r(2,3,20,18,1)+p('M2 7h20m-13 3 7 4-7 4z'),'Run macro in editor')
    add('assignmacro',badge(GLYPHS['basicideappear'][0],p('M13 20h9m-3-3 3 3-3 3')),'Assign macro arrow')
    add('scriptorganizer',r(3,3,18,18)+p('M3 8h18M8 8v13m4-10-2 3 2 3m5-6 2 3-2 3'),'Macro organizer panes')
    add('adddirect',badge(page()+lines(),plus(18,18))+p('M2 4v3'),'New document from templates')
    add('helpindex',c(12,12,10)+letter('?',8,5,.9),'Help question mark')
    add('optionstreedialog',p('M3 5h18M3 12h18M3 19h18')+r(6,2,4,6,1)+r(14,9,4,6,1)+r(7,16,4,6,1),'Settings sliders')
    add('colorsettings',p('M12 3C0 1-2 20 10 21c4 0 0-7 5-6 10 4 10-11-3-12z')+c(6,9,1)+c(11,6,1)+c(17,8,1),'Colour palette outline and wells')
    add('choosedesign',r(3,5,13,16,1)+p('M8 2h13v16M6 10h7M6 14h7'),'Design cards')
    add('themeselectorpanel',r(2,3,20,18)+p('M16 3v18')+r(5,7,8,10)+p('M18 7h2m-2 5h2m-2 5h2'),'Theme selector panel with preview')
    add('newwindow',r(7,7,15,14,1)+p('M4 17H2V2h15v2M7 11h15'),'New overlapping window')
    add('fullscreen',p('M3 9V3h6m6 0h6v6M3 15v6h6m6 0h6v-6'),'Fullscreen corner brackets')
    add('sidebar',r(2,3,20,18)+p('M15 3v18M18 7h2m-2 5h2m-2 5h2'),'Sidebar on right')
    add('toggletabbarvisibility',r(2,3,20,18)+p('M2 16h20M8 16v5M15 16v5'),'Document tab strip')
    add('ruler',r(2,7,20,10)+p('M6 7v6M10 7v3M14 7v6M18 7v3'),'Ruler ticks')
    add('attributepagesize',r(4,3,13,16)+p('M3 23h15m-15-2v2m5-2v2m5-2v2m5-2v2M21 3v16m-2-16h2m-2 5h2m-2 5h2m-2 6h2'),'Page dimensions beside rulers')
    add('orientation',r(3,2,11,16)+p('M17 9h5v12H6v-1M17 2a5 5 0 0 1 5 5m-3-2 3 2 1-4'),'Portrait and landscape orientation')
    add('pagemargin',r(3,2,18,20)+p('M7 6h10v12H7z'),'Page inset margins')
    add('pagedialog',badge(page()+r(8,9,8,8),transform(gear(),'translate(10 10) scale(.55)')),'Page properties')
    add('pagecolumntype',r(3,2,18,20)+p('M7 6h3m4 0h3M7 10h3m4 0h3M7 14h3m4 0h3M7 18h3m4 0h3'),'Page with two text columns')
