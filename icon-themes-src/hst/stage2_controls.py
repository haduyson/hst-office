    add('printlayout',page()+lines()+p('M2 2v20'),'Print layout with page edge guide')
    add('browseview',r(2,3,20,18)+p('M2 8h20M6 5h1m3 0h1M5 12h14M5 16h10'),'Web document browser view')
    add('showsinglepage',r(5,2,14,20)+p('M8 7h8M8 12h8M8 17h5'),'Single page view')
    add('showtwopages',r(2,4,9,16)+r(13,4,9,16)+p('M5 8h3m8 0h3M5 12h3m8 0h3'),'Two page view')
    add('showmultiplepages',r(3,2,7,9)+r(14,2,7,9)+r(3,14,7,9)+r(14,14,7,9),'Multiple page view')
