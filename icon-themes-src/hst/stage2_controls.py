    add('printpreview',badge(GLYPHS['print'][0],transform(glass,'translate(10 10) scale(.55)')),'Print preview magnifier')
    add('closepreview',badge(page()+c(11,11,4)+p('m14 14 4 4'),cross()),'Close document preview')
