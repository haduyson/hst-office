"""Stage 2 recipes: table and data families."""
from drawing import add, p, r, c, transform, arrow, grid, page, slide, plus, cross, check, badge, GLYPHS
from stage2_nouns import lines, pencil, small_pen, lock, bubble, eye, image_frame, book, chart, gear, clock_face, refresh, letter, circle_mark


def tables_and_data():
    for name,mark in [
        ('inserttable',plus()),('deletetable',cross()),('tabledialog',transform(gear(),'translate(10 10) scale(.55)')),
        ('tablenumberformatdialog',letter('#',14,14,.65)),('tabledesign',small_pen()),
        ('editprintarea',small_pen()),('addprintarea',plus()),('deleteprintarea',cross())]:
        base=grid()
        if 'printarea' in name:base=r(2,2,20,20)+r(6,6,12,12)
        add(name,badge(base,mark),'Table action: '+name)
    add('defineprintarea',r(3,3,18,18)+p('M7 7h10v10H7zM1 6V1h5M18 1h5v5M1 18v5h5M18 23h5v-5'),'Print area with crop corners')
    add('selecttable',grid()+p('m13 13 8 4-4 1-1 4z'),'Table selection pointer')
    add('entirecell',r(3,3,18,18)+r(8,8,8,8),'Single selected cell')
    add('mergecells',r(3,4,18,16)+p('M12 4v3m0 10v3M4 12h5m-2-2 2 2-2 2M20 12h-5m2-2-2 2 2 2'),'Merge cells inward')
    add('splitcell',r(3,4,18,16)+p('M12 4v16M9 12H5m2-2-2 2 2 2M15 12h4m-2-2 2 2-2 2'),'Split cell outward')
    add('splittable',r(3,3,18,6)+r(3,15,18,6)+p('M9 3v6m6-6v6M9 15v6m6-6v6M3 12h3m3 0h3m3 0h3m3 0h1'),'Separated table halves')
    add('optimizetable',grid()+p('M1 12h4m-2-2 2 2-2 2M23 12h-4m2-2-2 2 2 2'),'Fit table width')
    add('insertspreadsheet',grid()+p('M1 6V1h5'),'Embedded spreadsheet grid with corner tab')
    for name,col in [('insertcolumnsafter',True),('insertrowsafter',False)]:
        body=r(3,9,18,12,1)+p('M9 9v12M15 9v12')+plus(12,4) if col else r(9,3,12,18,1)+p('M9 9h12M9 15h12')+plus(4,12)
        add(name,body,'Insert after '+('column' if col else 'row'))
    add('borderdialog',r(3,3,18,18)+r(7,7,10,10),'Outer and inner borders')
    add('linestyle',p('M3 5h18M3 11h4m3 0h4m3 0h4M3 17h18M3 20h18'),'Border samples: solid, dashed and double')
    add('framelinecolor',r(3,3,18,18)+p('M7 17 12 6l5 11M9 13h6'),'Border colour symbol, neutral static base')
    add('xlinecolor',p('M5 15 16 4l4 4L9 19H5ZM14 6l4 4M4 22h16'),'Line colour pencil, neutral base for the dynamic swatch')
    add('formatline',p('M3 5h18M3 12h9M3 19h9')+small_pen(),'Edit line attributes')
    add('freezepanes',r(3,3,18,18)+p('M3 9h18M9 3v18M13 14h7m-3.5-3.5v7m-2.5-6 5 5m-5 0 5-5'),'Frozen pane with small snow crystal')
    add('splitwindow',r(2,3,20,18,1)+p('M2 8h20M12 8v13M9 8v13'),'Split window divider')
    add('togglesheetgrid',grid()+p('m2 22 20-20'),'Toggle sheet grid')
    add('viewrowcolumnheaders',r(3,3,18,18)+p('M3 8h18M8 3v18M13 3v5M18 3v5M3 13h5M3 18h5'),'Row and column header strips')
    add('viewcolumnrowhighlighting',r(3,3,18,18)+p('M3 9h18M3 15h18M9 3v18M15 3v18')+r(10.5,10.5,3,3),'Row and column intersection highlight')
    add('viewhiddencolrow',r(3,3,18,18)+p('M9 3v18M15 3v18m-3-16v4m0 4v4m0 4v2M3 12h4m-2-2 2 2-2 2'),'Hidden column marker')
    add('viewvaluehighlighting',r(3,3,18,18)+letter('1',7,6,.8)+p('M16 6v12'),'Value emphasis in grid')
    add('datadatapilotrun',r(3,3,18,18)+p('M3 8h18M8 3v18M11 12h7v6m-3-3 3 3 3-3'),'Pivot table turning arrow')
    add('recalcpivottable',badge(GLYPHS['datadatapilotrun'][0],transform(refresh(),'translate(10 10) scale(.55)')),'Refresh pivot table')
    add('deletepivottable',badge(GLYPHS['datadatapilotrun'][0],cross()),'Remove pivot table')
    add('dataconsolidate',r(2,3,7,7)+r(15,3,7,7)+p('M5 13l7 5 7-5')+r(8,18,8,4),'Consolidate two ranges')
    add('datasubtotals',p('M3 4h10M3 9h10M3 14h10M3 20h10M16 3h5l-3 8 3 9h-5'),'Subtotal rows and sigma bracket')
    add('datafilterstandardfilter',badge(GLYPHS['datafilterautofilter'][0],p('M14 15h8M14 19h8M17 13v4M20 17v4')),'Filter with adjustable criteria')
    add('datafilterspecialfilter',badge(GLYPHS['datafilterautofilter'][0],r(14,14,8,8)+p('M14 18h8M18 14v8')),'Filter by criteria range')
    add('removefiltersort',badge(GLYPHS['datafilterautofilter'][0],cross()),'Remove filter')
    add('sortdescending',p('M3 5h11m-11 6h8m-8 6h4M19 3v18m-3-3 3 3 3-3'),'Descending length bars')
    add('datasort',arrow('down',5,12,18)+arrow('up',19,12,18)+p('M10 6h4M10 12h4M10 18h4'),'Sort in either direction')
    add('texttocolumns',p('M3 3h18M3 7h18M12 9v3')+r(3,14,7,7)+r(14,14,7,7),'Text split into two columns')
    add('definename',r(2,4,20,16,1)+letter('N',5,7,.8)+plus(18,15),'Named range plus')
    add('label',p('M3 4h13l6 8-6 8H3z')+c(16,12,1.5),'Name tag')
    add('validation',badge(grid(),check()),'Cell validation check')
    add('protect',lock(),'Protect cells padlock')
    add('showinvalid',r(3,3,18,18)+c(12,12,6)+p('M12 8v5m0 3v.1'),'Invalid value circled')
    add('showerrors',p('m12 2 10 19H2zM12 8v6m0 3v.1'),'Error triangle')
    add('showdependents',r(2,2,7,6)+r(15,16,7,6)+p('M5 11v8h7m-3-3 3 3-3 3'),'Cell arrow toward dependents')
    add('showprecedents',r(2,2,7,6)+r(15,16,7,6)+p('M19 12V5h-7m3-3-3 3 3 3'),'Cell arrow toward precedents')
    add('cleararrowdependents',badge(GLYPHS['showdependents'][0],cross()),'Remove dependent trace')
    add('cleararrowprecedents',badge(GLYPHS['showprecedents'][0],cross()),'Remove precedent trace')
    add('auditingfillmode',r(3,3,18,18)+p('M3 9h18M9 3v18m3-7 7 4-4 1-1 4z'),'Trace fill pointer in cells')
    add('toggleformula',r(2,3,20,18)+letter('f',4,6,.9)+letter('x',13,9,.7),'Formula display in cell')
    add('calculate',r(4,2,16,20,2)+r(7,5,10,4)+p('M7 13h3m-1.5-1.5v3M14 13h3M7 18h3M14 17h3m-3 2h3'),'Calculator')
    add('automaticcalculation',badge(GLYPHS['calculate'][0],transform(refresh(),'translate(10 10) scale(.55)')),'Calculator with automatic loop')
    add('goalseekdialog',c(11,12,9)+c(11,12,5)+p('M11 12 21 2m-5 0h5v5'),'Target with incoming goal arrow')
    add('solverdialog',p('M2 18 8 11l5 3 9-12m-5 0h5v5M2 22h20'),'Constraint solution rising path')
    add('handleduplicaterecords',r(3,3,18,18)+p('M3 9h18M3 15h18M7 6h7M7 12h7m-5 6h9'),'Repeated rows and resolved result')
    add('shuffle',p('M3 5h3c6 0 6 14 12 14h3m-3-3 3 3-3 3M3 19h3c6 0 6-14 12-14h3m-3-3 3 3-3 3'),'Crossing shuffled arrows')
    add('insertsparkline',r(2,3,20,18)+p('m4 16 4-6 4 4 4-8 4 3'),'Sparkline inside a cell')
    add('drawchart',chart(),'Bar chart')
    add('descriptivestatisticsdialog',p('M3 21h18M6 17V9h4v8M14 17V5h4v12M4 3h6'),'Summary statistics bars and mean')
    add('analysisofvariancedialog',p('M3 21h18M6 5v12m-3-12h6m-6 12h6M17 2v10m-3-10h6m-6 10h6'),'Two groups with distinct variance ranges')
    add('correlationdialog',p('M3 3v18h18')+c(7,17,1)+c(10,12,1)+c(15,10,1)+c(19,5,1),'Correlated scatter points')
    add('covariancedialog',p('M3 3v18h18m-15-5 4-8 4 8 5-13M6 10l4 5 4-9 5 5'),'Two covarying traces')
    add('regressiondialog',p('M3 3v18h18M5 18 20 4')+c(7,13,.9)+c(13,14,.9)+c(17,4,.9),'Scatter with fitted regression line')
    add('fourieranalysisdialog',p('M2 12c3-14 7-14 10 0s7 14 10 0M2 21h20'),'Sinusoidal Fourier wave')
    for name,symbol in [('ttestdialog','t'),('ftestdialog','F'),('ztestdialog','Z')]:
        add(name,letter(symbol,2,2,.8)+p('M2 21h20M9 21c5 0 2-11 6-11s1 11 7 11'),symbol+' distribution test')
    add('chisquaretestdialog',letter('x',2,3,.9)+letter('2',12,2,.5)+p('M2 21h20M6 21c2-17 4-10 8-5l7 5'),'Chi-square test and skewed density')
    # Data source cylinders are hand-drawn cubic curves.
    db=p('M3 6c0-5 18-5 18 0s-18 5-18 0v12c0 5 18 5 18 0V6M3 12c0 5 18 5 18 0')
    add('dataprovider',db,'Data provider cylinder')
    add('dataproviderrefresh',badge(db,transform(refresh(),'translate(10 10) scale(.55)')),'Refresh data provider')
    add('insertexternaldatasource',badge(db,arrow('down',18,18,8)),'Import external data source')
    add('datastreams',badge(db,p('M14 14h8m-8 4h8m-8 4h8')),'Data stream lines')
    add('viewdatasourcebrowser',r(2,3,20,18,1)+p('M2 8h20M8 8v13M11 12h8M11 17h8'),'Data source browser panes')
    add('managexmlsource',p('m8 5-6 7 6 7m8-14 6 7-6 7M14 3l-4 18'),'XML source brackets')
    for name,sign in [('group',plus(18,18)),('ungroup',p('M15 18h6')),('showdetail',plus(18,18)),('hidedetail',p('M15 18h6'))]:
        base=p('M3 3h4v18H3M10 5h11M10 10h11M10 15h3M10 20h3')
        if name in ('showdetail','hidedetail'):base=p('M3 3v18M3 6h5m-5 6h5m-5 6h5M11 6h10M11 11h10')
        add(name,base+sign,'Outline rows: '+name)
